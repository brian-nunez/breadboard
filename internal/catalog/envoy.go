// Envoy as an infra proxy. Its admin API listens on 127.0.0.1 only, on the
// same port as the Envoy sidecar's (spec.EnvoyAdminPort), so the health
// check and the Envoy explorer read both the same way.
const (
	envoyConfigFile = "envoy.yaml"
	// Listener names, read by explorers and tests.
	envoyHTTPSListener       = "https"
	envoyPassthroughListener = "passthrough"
	// Passthrough clusters are tls_<route>, next to the L7 <route>.
	envoyPassthroughPrefix = "tls_"
)

// Type URLs of the Envoy extensions the generated config uses.
const (
	envoyTypeHCM       = "type.googleapis.com/envoy.extensions.filters.network.http_connection_manager.v3.HttpConnectionManager"
	envoyTypeRouter    = "type.googleapis.com/envoy.extensions.filters.http.router.v3.Router"
	envoyTypeTCPProxy  = "type.googleapis.com/envoy.extensions.filters.network.tcp_proxy.v3.TcpProxy"
	envoyTypeTLSInspec = "type.googleapis.com/envoy.extensions.filters.listener.tls_inspector.v3.TlsInspector"
	envoyTypeDownTLS   = "type.googleapis.com/envoy.extensions.transport_sockets.tls.v3.DownstreamTlsContext"
	envoyTypeUpTLS     = "type.googleapis.com/envoy.extensions.transport_sockets.tls.v3.UpstreamTlsContext"
	envoyTypeStdoutLog = "type.googleapis.com/envoy.extensions.access_loggers.stream.v3.StdoutAccessLog"
	// The DNS cluster extension (cluster_type envoy.clusters.dns), the
	// successor of type STRICT_DNS with dns_refresh_rate (D-162).
	envoyTypeDNSCluster = "type.googleapis.com/envoy.extensions.clusters.dns.v3.DnsCluster"
)

func envoy() *Entry {
	return &Entry{
		ID:        "envoy",
		Title:     "Envoy",
		Summary:   "Envoy proxy and load balancer: TLS on 8443, path routing, active health checks, re-encrypt, terminate and SNI passthrough.",
		Image:     "envoyproxy/envoy:v1.40.2",
		Listeners: HTTPProxyListeners(),
		Resources: Resources{Memory: "128m", CPUs: "0.25"},
		Notes:     notes("envoy"),
		Proxy: &Proxy{
			Modes:      []string{spec.TLSOn, spec.TLSOff, spec.TLSPassthrough},
			HTTP:       true,
			ConfigFile: envoyConfigFile,
			Unit:       envoyClusterName,
		},
		Server: func(s Server) Container {
			// The image has bash and openssl but no curl. Healthy means the
			// admin API reports Envoy initialized (GET /ready answers 200)
			// and the public listener completes a TLS handshake verified
			// against the lab CA by the service's name.
			check := strings.Join([]string{
				fmt.Sprintf(`exec 3<>/dev/tcp/127.0.0.1/%d`, spec.EnvoyAdminPort),
				`printf 'GET /ready HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n' >&3`,
				`head -n 1 <&3 | grep -q ' 200'`,
				fmt.Sprintf(`openssl s_client -connect %s:%d -servername %s -verify_hostname %s -verify_return_error -CAfile %s -brief < /dev/null > /dev/null 2>&1`,
					s.FQDN, ProxyHTTPSPort, s.FQDN, s.FQDN, CAFile),
			}, " && ")

			return Container{
				// The image's entrypoint runs Envoy as its envoy user. One
				// worker thread is plenty for a lab and keeps round robin
				// easy to watch: every connection shares one balancer.
				Command: []string{"envoy", "-c", ConfigDir + "/" + envoyConfigFile, "--concurrency", "1"},
				Files:   []File{{Name: envoyConfigFile, Data: envoyConfig(s)}},
				Health: Health{
					Test:          []string{"CMD", "bash", "-c", check},
					Interval:      10 * time.Second,
					Timeout:       5 * time.Second,
					Retries:       3,
					StartPeriod:   30 * time.Second,
					StartInterval: 1 * time.Second,
				},
			}
		},
		Client: ProxyClientEnv,
	}
}

// envoyClusterName is the cluster that balances an upstream.
func envoyClusterName(u Upstream) string {
	if u.Passthrough() {
		return envoyPassthroughPrefix + u.Name
	}

	return u.Name
}

// envoyConfig renders a readable, commented static bootstrap that learners
// can copy into their own file.
func envoyConfig(s Server) []byte {
	l7, pass := L7(s.Upstreams), Passthroughs(s.Upstreams)

	header := []string{fmt.Sprintf("envoy.yaml for %s, generated by Breadboard.", s.Name), ""}
	header = append(header, proxyRouteSummary(s.Upstreams)...)
	header = append(header, "",
		"To own this config, copy it next to experiment.yaml and set",
		fmt.Sprintf("services.%s.file. The certificate (%s, %s),", s.Name, CertFile, KeyFile),
		fmt.Sprintf("the lab CA (%s) and the trust bundle stay mounted; keep the", CAFile),
		fmt.Sprintf("admin API on 127.0.0.1:%d, which the health check reads.", spec.EnvoyAdminPort),
	)

	listeners := yseq{ym(
		ycomment(fmt.Sprintf("HTTPS on :%d with this service's certificate.", ProxyHTTPSPort)),
		"name", envoyHTTPSListener,
		"address", envoySocket("0.0.0.0", ProxyHTTPSPort),
		"filter_chains", yseq{ym(
			"filters", yseq{envoyHCM(s.Name, l7)},
			"transport_socket", ym(
				"name", "envoy.transport_sockets.tls",
				"typed_config", ym(
					"@type", envoyTypeDownTLS,
					"common_tls_context", ym(
						ycomment("TLS 1.2 or newer (Envoy's default, written out)."),
						"tls_params", ym("tls_minimum_protocol_version", "TLSv1_2"),
						"alpn_protocols", yseq{"h2", "http/1.1"},
						"tls_certificates", yseq{ym(
							"certificate_chain", ym("filename", CertFile),
							"private_key", ym("filename", KeyFile),
						)},
					),
				),
			),
		)},
	)}

	if len(pass) > 0 {
		var chains yseq
		for _, u := range pass {
			chains = append(chains, ym(
				ycomment(proxyModeComment(u)),
				"filter_chain_match", ym("server_names", yseq{u.ServerName}),
				"filters", yseq{ym(
					"name", "envoy.filters.network.tcp_proxy",
					"typed_config", ym(
						"@type", envoyTypeTCPProxy,
						"stat_prefix", envoyPassthroughPrefix+u.Name,
						"cluster", envoyClusterName(u),
						"access_log", envoyAccessLog(),
					),
				)},
			))
		}

		listeners = append(listeners, ym(
			ycomment(fmt.Sprintf("TLS on :%d routed by SNI without decrypting (passthrough).\n"+
				"The TLS inspector reads the server name from the client's hello;\n"+
				"a name no filter chain matches has no chain, so Envoy closes it.", ProxyPassthroughPort)),
			"name", envoyPassthroughListener,
			"address", envoySocket("0.0.0.0", ProxyPassthroughPort),
			"listener_filters", yseq{ym(
				"name", "envoy.filters.listener.tls_inspector",
				"typed_config", ym("@type", envoyTypeTLSInspec),
			)},
			"filter_chains", chains,
		))
	}

	clusters := yseq{}
	for _, u := range l7 {
		clusters = append(clusters, envoyCluster(u, envoyClusterName(u)))
	}

	for _, u := range pass {
		clusters = append(clusters, envoyCluster(u, envoyClusterName(u)))
	}

	resources := ym("listeners", listeners)
	if len(clusters) > 0 {
		resources = append(resources, yfield{key: "clusters", value: clusters})
	}

	doc := ym(
		"node", ym("id", s.Name, "cluster", s.Name),
		ycomment("Loopback only: the health check reads /ready; explorers read\n/clusters and /stats through docker exec."),
		"admin", ym("address", envoySocket("127.0.0.1", spec.EnvoyAdminPort)),
		"static_resources", resources,
	)

	return encodeYAMLDoc(header, doc)
}

// envoyHCM is the HTTP connection manager of the 8443 listener and its
// routes: one upstream takes everything; several are routed by /<name>/
// with the prefix rewritten to /, the first also taking every other path.
func envoyHCM(service string, l7 []Upstream) ymap {
	var routes yseq

	switch {
	case len(l7) == 0:
		routes = yseq{ym(
			ycomment("No upstream yet: every request gets 503."),
			"match", ym("prefix", "/"),
			"direct_response", ym("status", 503, "body", ym("inline_string", "breadboard: "+service+" has no upstream yet\n")),
		)}
	case len(l7) == 1:
		routes = yseq{ym(
			ycomment("Every request goes to "+l7[0].Service+"."),
			"match", ym("prefix", "/"),
			"route", ym("cluster", l7[0].Name),
		)}
	default:
		for _, u := range l7 {
			routes = append(routes, ym(
				ycomment(fmt.Sprintf("%s goes to %s with the prefix replaced by /.", u.Prefix(), u.Service)),
				"match", ym("prefix", u.Prefix()),
				"route", ym("cluster", u.Name, "prefix_rewrite", "/"),
			))
		}

		routes = append(routes, ym(
			ycomment("Routes match in order: every other path goes to the first upstream."),
			"match", ym("prefix", "/"),
			"route", ym("cluster", l7[0].Name),
		))
	}

	return ym(
		"name", "envoy.filters.network.http_connection_manager",
		"typed_config", ym(
			"@type", envoyTypeHCM,
			"stat_prefix", envoyHTTPSListener,
			"codec_type", "AUTO",
			ycomment("Envoy is the edge: it sets X-Forwarded-Proto from the connection\n(https) and appends the client's address to X-Forwarded-For."),
			"use_remote_address", true,
			"access_log", envoyAccessLog(),
			"route_config", ym(
				"name", service,
				"virtual_hosts", yseq{ym(
					"name", service,
					"domains", yseq{"*"},
					"routes", routes,
				)},
			),
			"http_filters", yseq{ym(
				"name", "envoy.filters.http.router",
				"typed_config", ym("@type", envoyTypeRouter),
			)},
		),
	)
}

// envoyCluster is one upstream: every address its Host resolves to,
// balanced round robin and actively health checked. Re-encrypt adds TLS
// verified against the lab CA for ServerName.
func envoyCluster(u Upstream, name string) ymap {
	check := ym(
		"timeout", "2s",
		"interval", "2s",
		ycomment("Check every 2s even before the first request (Envoy's default\nfor a cluster without traffic is 60s)."),
		"no_traffic_interval", "2s",
		"unhealthy_threshold", 3,
		"healthy_threshold", 2,
	)
	if u.Passthrough() {
		check = append(check, yfield{key: "tcp_health_check", value: ym(), comment: "A TCP connect: Envoy cannot speak the backend's TLS for the client."})
	} else {
		check = append(check, yfield{key: "http_health_check", value: ym(
			"host", u.ServerName,
			"path", "/",
			ycomment("Any answer below 500 means the server is up, so apps without a\nhandler for / stay in the rotation. Point path at a health endpoint\nand narrow this in your own copy."),
			"expected_statuses", yseq{ym("start", 200, "end", 500)},
		)})
	}

	c := ym(
		ycomment(proxyModeComment(u)),
		"name", name,
		ycomment(fmt.Sprintf("Strict DNS: every address %s resolves to is a host;\nEnvoy re-resolves it every 5s, so replicas that start later join.\nThe DNS cluster extension is the successor of the STRICT_DNS type\nand its deprecated dns_refresh_rate field.", u.Host)),
		"cluster_type", ym(
			"name", "envoy.clusters.dns",
			"typed_config", ym(
				"@type", envoyTypeDNSCluster,
				"dns_lookup_family", "V4_ONLY",
				"dns_refresh_rate", "5s",
			),
		),
		"connect_timeout", "2s",
		"lb_policy", "ROUND_ROBIN",
		"load_assignment", ym(
			"cluster_name", name,
			"endpoints", yseq{ym("lb_endpoints", yseq{ym("endpoint", ym("address", envoySocket(u.Host, u.Port)))})},
		),
		ycomment("Active checks: a host leaves the rotation after 3 failures and\ncomes back after 2 successes."),
		"health_checks", yseq{check},
	)
	if u.Mode == spec.TLSOn {
		c = append(c, yfield{key: "transport_socket", comment: "Re-encrypt: TLS with SNI " + u.ServerName + ", verified against the lab CA\nand matched to that name. Health checks use it too.", value: ym(
			"name", "envoy.transport_sockets.tls",
			"typed_config", ym(
				"@type", envoyTypeUpTLS,
				"sni", u.ServerName,
				"common_tls_context", ym("validation_context", ym(
					"trusted_ca", ym("filename", CAFile),
					"match_typed_subject_alt_names", yseq{ym("san_type", "DNS", "matcher", ym("exact", u.ServerName))},
				)),
			),
		)})
	}

	return c
}

func proxyModeComment(u Upstream) string {
	what := "every replica of " + u.Service
	if !u.App {
		what = u.Service
	}

	switch u.Mode {
	case spec.TLSOff:
		return fmt.Sprintf("Terminate: plaintext HTTP to %s on its private segment.\nReason: %s", what, u.Reason)
	case spec.TLSPassthrough:
		return fmt.Sprintf("Passthrough: the client's TLS session goes to %s untouched.", what)
	}

	return fmt.Sprintf("Re-encrypt: TLS to %s, verified as %s.", what, u.ServerName)
}

func envoyAccessLog() yseq {
	return yseq{ym("name", "envoy.access_loggers.stdout", "typed_config", ym("@type", envoyTypeStdoutLog))}
}

func envoySocket(addr string, port int) ymap {
	return ym("socket_address", ym("address", addr, "port_value", port))
}

// proxyRouteSummary describes a proxy's routes for a generated config's
// header comment.
func proxyRouteSummary(ups []Upstream) []string {
	l7, pass := L7(ups), Passthroughs(ups)

	var out []string
	if len(l7) == 0 {
		out = append(out, fmt.Sprintf("HTTPS on :%d has no upstream yet: every request gets 503.", ProxyHTTPSPort))
	} else {
		out = append(out, fmt.Sprintf("HTTPS on :%d with this service's certificate, then:", ProxyHTTPSPort))

		for i, u := range l7 {
			route := u.Prefix() + " (prefix stripped)"

			switch {
			case len(l7) == 1:
				route = "every request"
			case i == 0:
				route += ", and every other request"
			}

			out = append(out, fmt.Sprintf("  %s -> %s (%s)", route, u.Service, haproxyModeText(u)))
		}
	}

	if len(pass) > 0 {
		out = append(out, fmt.Sprintf("TLS on :%d is routed by SNI without decrypting (passthrough):", ProxyPassthroughPort))
		for _, u := range pass {
			out = append(out, fmt.Sprintf("  SNI %s -> %s, which presents its own certificate", u.ServerName, u.Service))
		}
	}

	return out
}
