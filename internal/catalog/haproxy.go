// HAProxy's loopback-only monitor frontend: the health check reads
// HAProxyMonitorURI, and explorers read the stats page (append ;csv for
// CSV) through docker exec. Nothing outside the container reaches it.
const (
	HAProxyMonitorPort = 8404
	HAProxyMonitorURI  = "/healthz"
	HAProxyStatsURI    = "/stats"
	haproxyConfigFile  = "haproxy.cfg"
	// haproxyMaxConn is the generated global maxconn: a fixed lab-sized
	// limit instead of HAProxy's automatic sizing from the fd limit.
	haproxyMaxConn = 256
)

func haproxy() *Entry {
	return &Entry{
		ID:        "haproxy",
		Title:     "HAProxy",
		Summary:   "HAProxy load balancer and reverse proxy: TLS on 8443, path routing, re-encrypt, terminate and SNI passthrough.",
		Image:     "haproxy:3.4.7",
		Listeners: HTTPProxyListeners(),
		Resources: Resources{Memory: "128m", CPUs: "0.25"},
		Notes:     notes("haproxy"),
		Proxy: &Proxy{
			Modes:      []string{spec.TLSOn, spec.TLSOff, spec.TLSPassthrough},
			HTTP:       true,
			ConfigFile: haproxyConfigFile,
			Unit:       haproxyBackend,
		},
		Server: func(s Server) Container {
			// The image has bash and openssl but no curl. Healthy means the
			// loopback monitor answers 200 and the public listener completes
			// a TLS handshake verified against the lab CA by the service's
			// name, so it also proves the certificate works.
			check := strings.Join([]string{
				fmt.Sprintf(`exec 3<>/dev/tcp/127.0.0.1/%d`, HAProxyMonitorPort),
				fmt.Sprintf(`printf 'GET %s HTTP/1.0\r\n\r\n' >&3`, HAProxyMonitorURI),
				`head -n 1 <&3 | grep -q ' 200 '`,
				fmt.Sprintf(`openssl s_client -connect %s:%d -servername %s -verify_hostname %s -verify_return_error -CAfile %s -brief < /dev/null > /dev/null 2>&1`,
					s.FQDN, ProxyHTTPSPort, s.FQDN, s.FQDN, CAFile),
			}, " && ")

			return Container{
				// The image's entrypoint adds -W -db (master-worker, foreground).
				Command: []string{"haproxy", "-f", ConfigDir + "/" + haproxyConfigFile},
				Files:   []File{{Name: haproxyConfigFile, Data: haproxyConfig(s)}},
				Health: Health{
					Test:          []string{"CMD", "bash", "-c", check},
					Interval:      10 * time.Second,
					Timeout:       5 * time.Second,
					Retries:       3,
					StartPeriod:   30 * time.Second,
					StartInterval: 1 * time.Second,
				},
			}
		},
		Client: ProxyClientEnv,
	}
}

// haproxyConfig renders a readable, commented haproxy.cfg that learners can
// copy into their own file.
func haproxyConfig(s Server) []byte {
	var b strings.Builder

	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	l7, pass := L7(s.Upstreams), Passthroughs(s.Upstreams)

	w("# haproxy.cfg for %s, generated by Breadboard.", s.Name)
	w("#")

	if len(l7) == 0 {
		w("# HTTPS on :%d has no upstream yet: every request gets 503.", ProxyHTTPSPort)
	} else {
		w("# HTTPS on :%d with this service's certificate, then:", ProxyHTTPSPort)

		for i, u := range l7 {
			route := u.Prefix() + " (prefix stripped)"

			switch {
			case len(l7) == 1:
				route = "every request"
			case i == 0:
				route += ", and every other request"
			}

			w("#   %s -> %s (%s)", route, u.Service, haproxyModeText(u))
		}
	}

	if len(pass) > 0 {
		w("# TLS on :%d is routed by SNI without decrypting (passthrough):", ProxyPassthroughPort)

		for _, u := range pass {
			w("#   SNI %s -> %s, which presents its own certificate", u.ServerName, u.Service)
		}
	}

	w("#")
	w("# To own this config, copy it next to experiment.yaml and set")
	w("# services.%s.file. The certificate (%s), the lab CA", s.Name, KeystoreFile)
	w("# (%s) and the trust bundle stay mounted; keep the monitor", CAFile)
	w("# frontend on 127.0.0.1:%d, which the health check reads.", HAProxyMonitorPort)
	w("")
	w("global")
	w("    # Logs go to the container's stdout: bb logs %s.", s.Name)
	w("    log stdout format raw local0")
	w("    # At most %d concurrent connections, on one thread. Without maxconn", haproxyMaxConn)
	w("    # HAProxy sizes its connection tables from the file-descriptor limit")
	w("    # (often a million inside Docker): about 90 MiB at idle, most of this")
	w("    # container's memory limit. For a load test, raise both in your own")
	w("    # copy (services.%s.file) and give the service more memory.", s.Name)
	w("    maxconn %d", haproxyMaxConn)
	w("    nbthread 1")
	w("    # TLS 1.2 or newer, towards clients and towards servers.")
	w("    ssl-default-bind-options ssl-min-ver TLSv1.2")
	w("    ssl-default-server-options ssl-min-ver TLSv1.2")
	w("")
	w("# Docker's embedded DNS. server-template lines keep resolving their name")
	w("# here, so HAProxy follows replicas as they start and stop.")
	w("resolvers docker")
	w("    nameserver dns 127.0.0.11:53")
	w("    accepted_payload_size 8192")
	w("    resolve_retries 3")
	w("    timeout resolve 1s")
	w("    timeout retry 1s")
	w("")
	w("defaults")
	w("    log global")
	w("    mode http")
	w("    option httplog")
	w("    timeout connect 5s")
	w("    timeout client 30s")
	w("    timeout server 30s")
	w("    timeout check 5s")
	w("    # Every server: an active check every 2s, down after 3 failures and up")
	w("    # after 2 successes. Addresses come from the docker resolvers; a server")
	w("    # whose name does not resolve yet starts down instead of failing.")
	w("    default-server inter 2s fall 3 rise 2 resolvers docker resolve-prefer ipv4 init-addr none")
	w("")
	w("# Loopback only: the health check and the stats page (%s;csv for CSV).", HAProxyStatsURI)
	w("frontend monitor")
	w("    bind 127.0.0.1:%d", HAProxyMonitorPort)
	w("    monitor-uri %s", HAProxyMonitorURI)
	w("    stats enable")
	w("    stats uri %s", HAProxyStatsURI)
	w("    stats refresh 10s")
	w("    # Server addresses on the stats page, so explorers can tell which")
	w("    # replica each server-template slot resolved to.")
	w("    stats show-legends")
	w("")
	w("frontend https")
	w("    bind :%d ssl crt %s alpn h2,http/1.1", ProxyHTTPSPort, KeystoreFile)
	w("    # Tell servers the client spoke HTTPS, and who the client was.")
	w("    http-request set-header X-Forwarded-Proto https")
	w("    option forwardfor")

	if len(l7) > 1 {
		for _, u := range l7 {
			w("    use_backend %s if { path_beg %s }", haproxyBackend(u), u.Prefix())
		}
	}

	if len(l7) > 0 {
		w("    default_backend %s", haproxyBackend(l7[0]))
	}

	for _, u := range l7 {
		w("")
		w("backend %s", haproxyBackend(u))
		w("%s", Comment("    # ", haproxyModeComment(u)))
		w("    balance roundrobin")

		if len(l7) > 1 {
			w("    http-request replace-path %s(.*) /\\1 if { path_beg %s }", u.Prefix(), u.Prefix())
		}

		w("    server-template %s %d %s %s", u.Name, max(len(u.Servers), 1), u.Addr(), haproxyServerOptions(u))
	}

	if len(pass) > 0 {
		w("")
		w("frontend passthrough")
		w("    bind :%d", ProxyPassthroughPort)
		w("    mode tcp")
		w("    option tcplog")
		w("    # Wait for the ClientHello, then route on its SNI. Unknown names are closed.")
		w("    tcp-request inspect-delay 5s")
		w("    tcp-request content accept if { req.ssl_hello_type 1 }")

		for _, u := range pass {
			w("    use_backend %s if { req.ssl_sni -i %s }", haproxyBackend(u), u.ServerName)
		}

		for _, u := range pass {
			w("")
			w("backend %s", haproxyBackend(u))
			w("%s", Comment("    # ", haproxyModeComment(u)))
			w("    mode tcp")
			w("    balance roundrobin")
			w("    server-template %s %d %s %s", u.Name, max(len(u.Servers), 1), u.Addr(), haproxyServerOptions(u))
		}
	}

	return []byte(b.String())
}

func haproxyBackend(u Upstream) string {
	if u.Passthrough() {
		return "be_tls_" + u.Name
	}

	return "be_" + u.Name
}

func haproxyModeText(u Upstream) string {
	switch u.Mode {
	case spec.TLSOff:
		return "terminate"
	case spec.TLSPassthrough:
		return "passthrough"
	}

	return "re-encrypt"
}

func haproxyModeComment(u Upstream) string {
	what := "every replica of " + u.Service
	if !u.App {
		what = u.Service
	}

	switch u.Mode {
	case spec.TLSOff:
		return fmt.Sprintf("terminate: plaintext HTTP to %s on its private segment. Reason: %s", what, u.Reason)
	case spec.TLSPassthrough:
		return fmt.Sprintf("passthrough: the client's TLS session goes to %s untouched; the check is a TCP connect.", what)
	}

	return fmt.Sprintf("re-encrypt: TLS to %s, verified against the lab CA as %s.", what, u.ServerName)
}

// haproxyServerOptions are a server-template's options for the hop's mode.
// The check is a TCP connect, over TLS (with verification) when the
// server line has ssl.
func haproxyServerOptions(u Upstream) string {
	if u.Mode != spec.TLSOn {
		return "check"
	}

	return fmt.Sprintf("ssl verify required ca-file %s sni str(%s) verifyhost %s check check-sni %s",
		CAFile, u.ServerName, u.ServerName, u.ServerName)
}
