package catalog

import "fmt"

// The host router (ADR-0017): the engine-owned Traefik service that makes a
// lab's host targets reachable from the host at
// https://<target>.<experiment>.localhost:<port>. It is the traefik entry's
// image, static configuration and health check with its own certificate
// store (the host certificate) and generated routes; a spec cannot replace
// them.
const (
	// HostCertFile and HostKeyFile are where the router finds the host
	// certificate from the host CA. Only the router mounts them.
	HostCertFile = "/etc/bb/host/tls.crt"
	HostKeyFile  = "/etc/bb/host/tls.key"
	// HostRouterPort is the router's HTTPS entrypoint inside the
	// container, published on 127.0.0.1:<host port>.
	HostRouterPort = ProxyHTTPSPort
	// Router, service and transport names: target-<target> for a target's
	// shared host name, instance-<instance> for one replica's. Targets and
	// instances share the lab's one service namespace, and the prefixes
	// keep the two kinds apart, so no two names collide.
	hostTargetPrefix   = "target-"
	hostInstancePrefix = "instance-"
)

// HostTarget is one app or infra service the host router serves.
type HostTarget struct {
	// Target is the app or service in experiment.yaml.
	Target string
	// App marks an app target, which may run several replicas.
	App bool
	// Name is the host name: <target>.<experiment>.localhost.
	Name string
	// ServerName is the name the router verifies on every instance's lab
	// certificate (and sends as SNI): <target>.<domain>.
	ServerName string
	// Port is the TLS port on every instance: the app's host port, or the
	// infra service's first HTTPS listener.
	Port int
	// Instances are where the router sends requests, in instance order.
	Instances []HostInstance
}

// HostInstance is one instance of a host target.
type HostInstance struct {
	// Service is the instance's service name (api-2, or api with one
	// replica).
	Service string
	// FQDN is the instance's own lab name, the router's dial address and,
	// for an instance route, the verified name.
	FQDN string
	// Name is the host name that reaches this instance alone
	// (<app>-<n>.<experiment>.localhost); empty for a target with one
	// instance.
	Name string
}

// HostNames lists every host name of the targets, in route order: each
// target's name, then its instances' names.
func HostNames(targets []HostTarget) []string {
	var out []string
	for _, t := range targets {
		out = append(out, t.Name)
		for _, inst := range t.Instances {
			if inst.Name != "" {
				out = append(out, inst.Name)
			}
		}
	}

	return out
}

// HostRouter renders the host router's container: Traefik with the
// traefik entry's static configuration and health check, the host
// certificate as its default certificate, and one route per host name.
func HostRouter(s Server) Container {
	return traefikContainer(hostRouterStaticConfig(s), hostRouterTLSConfig(s), hostRouterDynamicConfig(s))
}

func hostRouterStaticConfig(s Server) []byte {
	header := []string{
		fmt.Sprintf("traefik.yml for %s, generated by Breadboard: the static configuration", s.Name),
		"of the lab's host router. The routes in " + traefikDynamicDir + "/" + traefikConfigFile + " are",
		"generated from every host target in experiment.yaml; the router has no file.",
	}

	return encodeYAMLDoc(header, traefikStaticDoc(Server{Name: s.Name}, "the host certificate from the host CA"))
}

func hostRouterTLSConfig(s Server) []byte {
	header := []string{
		fmt.Sprintf("tls.yml for %s, generated by Breadboard: the host certificate,", s.Name),
		"signed by the install's host CA for exactly the lab's *.localhost host",
		"names, and the minimum TLS version. The lab certificate in " + TLSDir,
		"is not presented to the host.",
	}
	doc := ym("tls", ym(
		"stores", ym("default", ym("defaultCertificate", ym("certFile", HostCertFile, "keyFile", HostKeyFile))),
		ycomment("TLS 1.2 or newer towards host clients."),
		"options", ym("default", ym("minVersion", "VersionTLS12")),
	))

	return encodeYAMLDoc(header, doc)
}

// hostRouterDynamicConfig routes each host name to its target: a target's
// name to every instance (weighted round robin), an instance's name to
// that instance alone. Every hop re-encrypts and verifies the instance's
// lab certificate against the lab CA.
func hostRouterDynamicConfig(s Server) []byte {
	header := []string{
		fmt.Sprintf("%s for %s, generated by Breadboard: the host router's routes.", traefikConfigFile, s.Name),
		"",
	}
	for _, t := range s.HostTargets {
		header = append(header, fmt.Sprintf("  https://%s -> %s (%s)", t.Name, t.Target, instances(len(t.Instances))))
		for _, inst := range t.Instances {
			if inst.Name != "" {
				header = append(header, fmt.Sprintf("  https://%s -> %s", inst.Name, inst.Service))
			}
		}
	}

	header = append(header, "",
		"A name no router claims gets Traefik's 404. Each request reaches its",
		"target over TLS, verified against the lab CA ("+CAFile+"), with the",
		"original Host header and Traefik's X-Forwarded-* headers.",
	)

	routers, services, transports := ym(), ym(), ym()
	route := func(key, name, serverName, comment string, port int, insts []HostInstance) {
		routers = append(routers, yfield{key: key, comment: comment, value: ym(
			"entryPoints", yseq{traefikEntrypoint},
			"rule", "Host(`"+name+"`)",
			"service", key,
		)})

		var servers yseq
		for _, inst := range insts {
			servers = append(servers, ym("url", fmt.Sprintf("https://%s:%d", inst.FQDN, port)))
		}

		lb := ym("strategy", "wrr", "servers", servers, "passHostHeader", true, "serversTransport", key)
		services = append(services, yfield{key: key, value: ym("loadBalancer", lb)})
		transports = append(transports, yfield{key: key, comment: fmt.Sprintf("Re-encrypt: TLS with SNI %s, verified against the lab CA.", serverName), value: ym(
			"serverName", serverName,
			"rootCAs", yseq{CAFile},
		)})
	}

	for _, t := range s.HostTargets {
		what := t.Target
		if len(t.Instances) > 1 {
			what = fmt.Sprintf("every instance of %s (weighted round robin)", t.Target)
		}

		route(hostTargetPrefix+t.Target, t.Name, t.ServerName, fmt.Sprintf("https://%s reaches %s.", t.Name, what), t.Port, t.Instances)

		for _, inst := range t.Instances {
			if inst.Name == "" {
				continue
			}

			route(hostInstancePrefix+inst.Service, inst.Name, inst.FQDN, fmt.Sprintf("https://%s reaches %s alone.", inst.Name, inst.Service), t.Port, []HostInstance{inst})
		}
	}

	http := ym("routers", routers, "services", services)
	if len(transports) > 0 {
		http = append(http, yfield{key: "serversTransports", value: transports})
	}

	return traefikLiteral(encodeYAMLDoc(header, ym("http", http)))
}

// instances counts instances in words: 1 instance, 3 instances.
func instances(n int) string {
	if n == 1 {
		return "1 instance"
	}

	return fmt.Sprintf("%d instances", n)
}
