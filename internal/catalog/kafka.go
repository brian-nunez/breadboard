package catalog

import (
	"fmt"
	"strings"
	"time"
)

func kafka() *Entry {
	const (
		sslPort        = 9093
		plainPort      = 9092
		controllerPort = 9094
		dataDir        = "/var/lib/kafka/data"
	)
	return &Entry{
		ID:      "kafka",
		Title:   "Kafka",
		Summary: "Apache Kafka event streaming: a single broker in KRaft mode, SSL on 9093.",
		Image:   "apache/kafka:4.3.2",
		Listeners: []Listener{
			{Name: "ssl", Protocol: "kafka", Port: sslPort, PlaintextPort: plainPort},
		},
		Resources: Resources{Memory: "1g", CPUs: "1.0"},
		Secrets: []Secret{
			{Key: "cluster-id", Kind: ClusterID, Help: "KRaft cluster id used to format the log directory"},
		},
		DataPath: dataDir,
		Notes:    notes("kafka"),
		Server: func(s Server) Container {
			listeners := []string{fmt.Sprintf("SSL://0.0.0.0:%d", sslPort), fmt.Sprintf("CONTROLLER://localhost:%d", controllerPort)}
			advertised := []string{fmt.Sprintf("SSL://%s:%d", s.FQDN, sslPort)}
			protocols := []string{"SSL:SSL", "CONTROLLER:PLAINTEXT"}
			if s.Plain != nil {
				// Bound to the private segment's address only, so nothing
				// outside that segment can reach the unencrypted port.
				listeners = append(listeners, fmt.Sprintf("PLAINTEXT://%s:%d", s.Plain.Address, plainPort))
				advertised = append(advertised, fmt.Sprintf("PLAINTEXT://%s:%d", s.Plain.FQDN, plainPort))
				protocols = append(protocols, "PLAINTEXT:PLAINTEXT")
			}
			props := []string{
				"# Generated by Breadboard. Single node: this process is both broker and KRaft controller.",
				"process.roles=broker,controller",
				"node.id=1",
				fmt.Sprintf("controller.quorum.voters=1@localhost:%d", controllerPort),
				"controller.listener.names=CONTROLLER",
				"# The controller listener is loopback-only inside the container; clients never use it.",
				"listeners=" + strings.Join(listeners, ","),
				"advertised.listeners=" + strings.Join(advertised, ","),
				"listener.security.protocol.map=" + strings.Join(protocols, ","),
				"inter.broker.listener.name=SSL",
				"log.dirs=" + dataDir,
				"num.partitions=1",
				"# One broker, so internal topics cannot be replicated.",
				"offsets.topic.replication.factor=1",
				"transaction.state.log.replication.factor=1",
				"transaction.state.log.min.isr=1",
				"share.coordinator.state.topic.replication.factor=1",
				"share.coordinator.state.topic.min.isr=1",
				"# Topics are created on purpose, with the admin client, never by a typo.",
				"auto.create.topics.enable=false",
				"group.initial.rebalance.delay.ms=0",
				"# TLS from PEM files directly: no Java keystores.",
				"ssl.keystore.type=PEM",
				"ssl.keystore.location=" + KeystoreFile,
				"ssl.truststore.type=PEM",
				"ssl.truststore.location=" + CAFile,
				"ssl.client.auth=none",
				"ssl.endpoint.identification.algorithm=https",
			}
			client := strings.Join([]string{
				"security.protocol=SSL",
				"ssl.truststore.type=PEM",
				"ssl.truststore.location=" + CAFile,
				"ssl.endpoint.identification.algorithm=https",
			}, "\n") + "\n"
			start := strings.Join([]string{
				"set -e",
				"/opt/kafka/bin/kafka-storage.sh format --ignore-formatted --cluster-id \"$$KAFKA_CLUSTER_ID\" --config " + ConfigDir + "/server.properties",
				"exec /opt/kafka/bin/kafka-server-start.sh " + ConfigDir + "/server.properties",
			}, "\n")
			return Container{
				Entrypoint: []string{"/bin/sh", "-c", start},
				Environment: []EnvVar{
					{Name: "KAFKA_CLUSTER_ID", Value: s.Secret("cluster-id"), Secret: true},
					{Name: "KAFKA_HEAP_OPTS", Value: "-Xms256m -Xmx512m"},
				},
				Files: []File{
					{Name: "server.properties", Data: []byte(strings.Join(props, "\n") + "\n")},
					{Name: "client.properties", Data: []byte(client)},
				},
				Health: Health{
					// An API versions request over SSL against the FQDN: healthy
					// also proves the certificate verifies.
					Test: []string{"CMD-SHELL", fmt.Sprintf(
						"KAFKA_HEAP_OPTS=-Xmx128m /opt/kafka/bin/kafka-broker-api-versions.sh --bootstrap-server %s:%d --command-config %s/client.properties > /dev/null",
						s.FQDN, sslPort, ConfigDir)},
					Interval:      15 * time.Second,
					Timeout:       30 * time.Second,
					Retries:       10,
					StartPeriod:   90 * time.Second,
					StartInterval: 5 * time.Second,
				},
			}
		},
		Client: func(c Client) []EnvVar {
			if c.Plain != nil {
				return []EnvVar{
					{Name: "KAFKA_BROKERS", Value: fmt.Sprintf("%s:%d", c.Plain.FQDN, plainPort)},
					{Name: "KAFKA_SECURITY_PROTOCOL", Value: "PLAINTEXT"},
				}
			}
			return []EnvVar{
				{Name: "KAFKA_BROKERS", Value: fmt.Sprintf("%s:%d", c.FQDN, sslPort)},
				{Name: "KAFKA_SECURITY_PROTOCOL", Value: "SSL"},
			}
		},
	}
}
