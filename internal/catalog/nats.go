package catalog

import (
	"fmt"
	"strings"
	"time"
)

const (
	// NatsClientPort is NATS's TLS client port.
	NatsClientPort = 4222
	// NatsMonitorPort is NATS's loopback-only HTTP monitoring port.
	NatsMonitorPort = 8222
)

func natsEntry() *Entry {
	return &Entry{
		ID:      "nats",
		Title:   "NATS",
		Summary: "Lightweight messaging and JetStream persistence: TLS on 4222, token auth, loopback monitoring.",
		Image:   "nats:2.15.3-alpine3.22",
		// NATS serves one client listener block per server; no separate
		// segment-confined plaintext port is offered in v1.
		Listeners: []Listener{
			{Name: "nats", Protocol: "nats", Port: NatsClientPort},
		},
		Resources: Resources{Memory: "128m", CPUs: "0.5"},
		Secrets: []Secret{
			{Key: "token", Kind: Password, Help: "NATS client authorization token"},
		},
		Config: []ConfigOption{
			{
				Key:     "jetstream",
				Default: "true",
				Help:    "enable JetStream persistence (true or false)",
				Validate: func(v string) error {
					if v != "true" && v != "false" {
						return fmt.Errorf("jetstream %q: must be true or false", v)
					}

					return nil
				},
			},
		},
		DataPath: "/data",
		Notes:    notes("nats"),
		Server: func(s Server) Container {
			jsEnabled := s.Config["jetstream"] != "false"

			return Container{
				// Pass --auth via shell env expansion so nats.conf never holds a literal secret.
				Entrypoint: []string{
					"/bin/sh", "-c",
					fmt.Sprintf(`exec nats-server -c %s/nats.conf --auth "$NATS_TOKEN"`, ConfigDir),
				},
				Environment: []EnvVar{
					{Name: "NATS_TOKEN", Value: s.Secret("token"), Secret: true},
				},
				Files: []File{
					{Name: "nats.conf", Data: []byte(natsConfig(s, jsEnabled))},
				},
				Health: Health{
					// Confirms server + JetStream readiness and that TLS loaded on the client port.
					Test: []string{
						"CMD-SHELL",
						fmt.Sprintf(
							`wget -qO- http://127.0.0.1:%d/healthz >/dev/null && wget -qO- http://127.0.0.1:%d/varz | grep -Eq '"tls_required":[[:space:]]*true'`,
							NatsMonitorPort, NatsMonitorPort,
						),
					},
					Interval:      5 * time.Second,
					Timeout:       3 * time.Second,
					Retries:       10,
					StartPeriod:   10 * time.Second,
					StartInterval: 500 * time.Millisecond,
				},
			}
		},
		Client: func(c Client) []EnvVar {
			return []EnvVar{
				{Name: "NATS_URL", Value: fmt.Sprintf("tls://%s:%d", c.FQDN, NatsClientPort)},
				{Name: "NATS_TOKEN", Value: c.Secret("token"), Secret: true},
				{Name: "NATS_CA", Value: CAFile},
			}
		},
	}
}

func natsConfig(s Server, jetstream bool) string {
	lines := []string{
		"# Generated by Breadboard for " + s.Name + ".",
		fmt.Sprintf("server_name: %q", s.Name),
		fmt.Sprintf("listen: 0.0.0.0:%d", NatsClientPort),
		fmt.Sprintf("http: 127.0.0.1:%d", NatsMonitorPort),
		"",
		"tls {",
		fmt.Sprintf("  cert_file: %q", CertFile),
		fmt.Sprintf("  key_file: %q", KeyFile),
		fmt.Sprintf("  ca_file: %q", CAFile),
		"  timeout: 5",
		"}",
	}

	if jetstream {
		lines = append(lines,
			"",
			"jetstream {",
			`  store_dir: "/data"`,
			"  max_memory_store: 64MB",
			"  max_file_store: 512MB",
			"}",
		)
	}

	lines = append(lines, "")

	return strings.Join(lines, "\n")
}
