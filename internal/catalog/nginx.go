// NGINX's loopback-only status server: the health check reads
// NginxHealthURI, and explorers read stub_status (NginxStatusURI) through
// docker exec. Nothing outside the container reaches it.
const (
	NginxStatusPort = 8404
	NginxHealthURI  = "/healthz"
	NginxStatusURI  = "/stub_status"
	nginxConfigFile = "nginx.conf"
	// nginxHealthAgent is the health check's user agent, left out of the
	// access log.
	nginxHealthAgent = "bb-healthcheck"
)

func nginx() *Entry {
	return &Entry{
		ID:        "nginx",
		Title:     "NGINX",
		Summary:   "NGINX reverse proxy: TLS on 8443, path routing, re-encrypt, terminate, and SNI passthrough with the stream module.",
		Image:     "nginx:1.30.6-alpine",
		Listeners: HTTPProxyListeners(),
		Resources: Resources{Memory: "64m", CPUs: "0.25"},
		Notes:     notes("nginx"),
		Proxy: &Proxy{
			Modes:      []string{spec.TLSOn, spec.TLSOff, spec.TLSPassthrough},
			HTTP:       true,
			ConfigFile: nginxConfigFile,
		},
		Server: func(s Server) Container {
			// The image has wget and curl, no openssl. Healthy means the
			// loopback status server answers 200, and the public listener
			// completes a TLS handshake verified against the lab CA by the
			// service's name and answers HTTP. The request is a TRACE, which
			// NGINX refuses itself (405) without calling an upstream, so
			// health checks never reach the backends; its user agent keeps
			// it out of the access log.
			check := strings.Join([]string{
				fmt.Sprintf("wget -q -O /dev/null http://127.0.0.1:%d%s", NginxStatusPort, NginxHealthURI),
				fmt.Sprintf("curl -s -o /dev/null --max-time 3 --cacert %s -A %s -X TRACE https://%s:%d/", CAFile, nginxHealthAgent, s.FQDN, ProxyHTTPSPort),
			}, " && ")

			return Container{
				// Straight to nginx: the image's entrypoint scripts edit
				// /etc/nginx/conf.d, which this config does not use.
				Entrypoint: []string{"nginx", "-c", ConfigDir + "/" + nginxConfigFile},
				Files:      []File{{Name: nginxConfigFile, Data: nginxConfig(s)}},
				Health: Health{
					Test:          []string{"CMD", "sh", "-c", check},
					Interval:      10 * time.Second,
					Timeout:       5 * time.Second,
					Retries:       3,
					StartPeriod:   30 * time.Second,
					StartInterval: 1 * time.Second,
				},
			}
		},
		Client: ProxyClientEnv,
	}
}

// nginxConfig renders a readable, commented nginx.conf that learners can
// copy into their own file.
func nginxConfig(s Server) []byte {
	var b strings.Builder

	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	l7, pass := L7(s.Upstreams), Passthroughs(s.Upstreams)

	w("# nginx.conf for %s, generated by Breadboard.", s.Name)
	w("#")

	if len(l7) == 0 {
		w("# HTTPS on :%d has no upstream yet: every request gets 503.", ProxyHTTPSPort)
	} else {
		w("# HTTPS on :%d with this service's certificate, then:", ProxyHTTPSPort)

		for i, u := range l7 {
			route := u.Prefix() + " (prefix stripped)"

			switch {
			case len(l7) == 1:
				route = "every request"
			case i == 0:
				route += ", and every other request"
			}

			w("#   %s -> %s (%s)", route, u.Service, haproxyModeText(u))
		}
	}

	if len(pass) > 0 {
		w("# TLS on :%d is routed by SNI without decrypting (passthrough):", ProxyPassthroughPort)

		for _, u := range pass {
			w("#   SNI %s -> %s, which presents its own certificate", u.ServerName, u.Service)
		}
	}

	w("#")
	w("# To own this config, copy it next to experiment.yaml and set")
	w("# services.%s.file. The certificate (%s, %s),", s.Name, CertFile, KeyFile)
	w("# the lab CA (%s) and the trust bundle stay mounted; keep the", CAFile)
	w("# status server on 127.0.0.1:%d, which the health check reads.", NginxStatusPort)
	w("")
	w("# Runs in the foreground, so the container lives as long as NGINX.")
	w("daemon off;")
	w("user nginx;")
	w("# One worker keeps round robin easy to watch; raise it for throughput.")
	w("worker_processes 1;")
	w("pid /run/nginx.pid;")
	w("# Logs go to the container's output: bb logs %s.", s.Name)
	w("error_log /dev/stderr notice;")
	w("")
	w("events {")
	w("    worker_connections 1024;")
	w("}")
	w("")
	w("http {")
	w("    include /etc/nginx/mime.types;")
	w("    # Every request is logged, except the health check's (a TRACE to :%d", ProxyHTTPSPort)
	w("    # every 10s, which NGINX refuses itself with 405).")
	w("    map $http_user_agent $bb_access_log {")
	w("        %s 0;", nginxHealthAgent)
	w("        default 1;")
	w("    }")
	w("    access_log /dev/stdout combined if=$bb_access_log;")
	w("    # Docker's embedded DNS. Upstream servers marked resolve keep resolving")
	w("    # their name here (every 5s), so NGINX follows replicas as they start")
	w("    # and stop.")
	w("    resolver 127.0.0.11 valid=5s ipv6=off;")
	w("")
	w("    # Loopback only: the health check and the stub_status counters.")
	w("    server {")
	w("        listen 127.0.0.1:%d;", NginxStatusPort)
	w("        access_log off;")
	w("        location = %s {", NginxHealthURI)
	w("            return 200 \"ok\\n\";")
	w("        }")
	w("        location = %s {", NginxStatusURI)
	w("            stub_status;")
	w("        }")
	w("    }")

	for _, u := range l7 {
		w("")
		w("%s", Comment("    # ", haproxyModeComment(u)))
		w("    upstream %s {", nginxUpstream(u))
		nginxUpstreamBody(w, u, true)
		w("    }")
	}

	w("")
	w("    server {")
	w("        listen %d ssl;", ProxyHTTPSPort)
	w("        http2 on;")
	w("        server_name %s;", s.FQDN)
	w("        ssl_certificate %s;", CertFile)
	w("        ssl_certificate_key %s;", KeyFile)
	w("        ssl_protocols TLSv1.2 TLSv1.3;")

	if len(l7) == 0 {
		w("")
		w("        location / {")
		w("            return 503;")
		w("        }")
	}

	w("")
	w("        # Every proxied request: tell the backend the client spoke HTTPS and")
	w("        # who the client was, and keep the client's Host header. HTTP/1.1")
	w("        # without a Connection header lets upstream connections be reused.")
	w("        proxy_http_version 1.1;")
	w("        proxy_set_header Connection \"\";")
	w("        proxy_set_header Host $host;")
	w("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;")
	w("        proxy_set_header X-Forwarded-Proto https;")
	w("        proxy_connect_timeout 5s;")

	for i, u := range l7 {
		if len(l7) == 1 {
			nginxLocation(w, "/", u, false)

			continue
		}

		if i == 0 {
			nginxLocation(w, "/", u, false)
		}

		nginxLocation(w, u.Prefix(), u, true)
	}

	w("    }")
	w("}")

	if len(pass) > 0 {
		w("")
		w("# Passthrough: TCP on :%d, routed by the SNI in the client's ClientHello.", ProxyPassthroughPort)
		w("# NGINX never decrypts, so the client sees the backend's own certificate.")
		w("stream {")
		w("    resolver 127.0.0.11 valid=5s ipv6=off;")
		w("")
		w("    map $ssl_preread_server_name $bb_passthrough {")

		for _, u := range pass {
			w("        %s %s;", u.ServerName, nginxUpstream(u))
		}

		w("        # Names no upstream claims go nowhere: the connection is closed.")
		w("        default bb_unknown_sni;")
		w("    }")
		w("")
		w("    upstream bb_unknown_sni {")
		w("        server 127.0.0.1:1 down;")
		w("    }")

		for _, u := range pass {
			w("")
			w("%s", Comment("    # ", haproxyModeComment(u)))
			w("    upstream %s {", nginxUpstream(u))
			nginxUpstreamBody(w, u, false)
			w("    }")
		}

		w("")
		w("    server {")
		w("        listen %d;", ProxyPassthroughPort)
		w("        ssl_preread on;")
		w("        proxy_connect_timeout 5s;")
		w("        proxy_pass $bb_passthrough;")
		w("    }")
		w("}")
	}

	return []byte(b.String())
}

// nginxUpstream names an upstream block.
func nginxUpstream(u Upstream) string {
	if u.Passthrough() {
		return "tls_" + u.Name
	}

	return "be_" + u.Name
}

// nginxUpstreamBody writes an upstream block's contents: a shared-memory
// zone (resolve needs one), one server line that resolves the hop's name
// to every instance, and passive health checks.
func nginxUpstreamBody(w func(string, ...any), u Upstream, http bool) {
	w("        # Round robin (the default) across every address %s resolves to.", u.Host)
	w("        zone %s 64k;", nginxUpstream(u))
	w("        # Passive health: after 3 failed attempts within 10s, an address rests")
	w("        # for 10s. (Active health_check is NGINX Plus only.)")
	w("        server %s resolve max_fails=3 fail_timeout=10s;", u.Addr())

	if http {
		w("        # Idle connections kept open per worker, so requests skip the handshake.")
		w("        keepalive 16;")
	}
}

// nginxLocation writes one location that proxies to u. strip replaces the
// location's prefix with / (a proxy_pass with a URI part).
func nginxLocation(w func(string, ...any), path string, u Upstream, strip bool) {
	scheme := "https"
	if u.Mode == spec.TLSOff {
		scheme = "http"
	}

	uri := ""
	if strip {
		uri = "/"
	}

	w("")

	switch {
	case strip:
		w("        # %s -> %s, with the prefix replaced by /.", path, u.Service)
	default:
		w("        # Every other request -> %s.", u.Service)
	}

	w("        location %s {", path)
	w("            proxy_pass %s://%s%s;", scheme, nginxUpstream(u), uri)

	if u.Mode == spec.TLSOn {
		w("            # Re-encrypt: verify the backend against the lab CA as %s,", u.ServerName)
		w("            # and send that name as SNI.")
		w("            proxy_ssl_verify on;")
		w("            proxy_ssl_trusted_certificate %s;", CAFile)
		w("            proxy_ssl_verify_depth 2;")
		w("            proxy_ssl_server_name on;")
		w("            proxy_ssl_name %s;", u.ServerName)
		w("            proxy_ssl_protocols TLSv1.2 TLSv1.3;")
		w("            proxy_ssl_session_reuse on;")
	}

	w("        }")
}
