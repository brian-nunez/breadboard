package catalog

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"time"
)

const (
	// OpenSearchHTTPPort is OpenSearch's HTTPS REST API port.
	OpenSearchHTTPPort = 9200
	// OpenSearchTransportPort is OpenSearch's internal transport port (bound to 127.0.0.1 only).
	OpenSearchTransportPort = 9300
)

var opensearchIndexName = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]{0,254}$`)

// ParseOpenSearchIndices validates and returns the normalized index names in
// config.indices (empty slice when unset).
func ParseOpenSearchIndices(raw string) ([]string, error) {
	if raw == "" {
		return nil, nil
	}

	if strings.Contains(raw, " ") {
		return nil, errors.New("separate indices with commas, no spaces")
	}

	var out []string

	seen := map[string]bool{}

	for _, name := range strings.Split(raw, ",") {
		if name == "" {
			continue
		}

		if name == "." || name == ".." || !opensearchIndexName.MatchString(name) {
			return nil, fmt.Errorf("index %q: must start with a-z or 0-9 and contain only a-z, 0-9, '.', '_' or '-'", name)
		}

		if !seen[name] {
			seen[name] = true
			out = append(out, name)
		}
	}

	return out, nil
}

func opensearch() *Entry {
	return &Entry{
		ID:      "opensearch",
		Title:   "OpenSearch",
		Summary: "Distributed search and analytics engine (single-node): HTTPS on 9200, TLS-verified, generated admin password.",
		Image:   "opensearchproject/opensearch:3.10.0",
		// OpenSearch serves one HTTP port per node, so a plaintext listener
		// could not be confined to a private segment alongside HTTPS.
		Listeners: []Listener{
			{Name: "https", Protocol: "https", Port: OpenSearchHTTPPort},
		},
		Resources: Resources{Memory: "1536m", CPUs: "1.0"},
		Secrets: []Secret{
			{Key: "password", Kind: Password, Help: "OpenSearch admin user password"},
		},
		Config: []ConfigOption{
			{
				Key:     "indices",
				Default: "",
				Help:    "comma-separated indices created at startup",
				Validate: func(v string) error {
					_, err := ParseOpenSearchIndices(v)

					return err
				},
			},
		},
		DataPath: "/usr/share/opensearch/data",
		Notes:    notes("opensearch"),
		Server: func(s Server) Container {
			endpoint := fmt.Sprintf("https://%s:%d", s.FQDN, OpenSearchHTTPPort)
			healthURL := endpoint + "/_cluster/health?wait_for_status=yellow&timeout=5s"

			return Container{
				Entrypoint: []string{"/bin/bash", ConfigDir + "/start.sh"},
				Environment: []EnvVar{
					{Name: "DISABLE_INSTALL_DEMO_CONFIG", Value: "true"},
					{Name: "DISABLE_PERFORMANCE_ANALYZER_AGENT_CLI", Value: "true"},
					{Name: "OPENSEARCH_JAVA_OPTS", Value: "-Xms512m -Xmx512m"},
					{Name: "OPENSEARCH_PASSWORD", Value: s.Secret("password"), Secret: true},
					{Name: "BB_INDICES", Value: s.Config["indices"]},
				},
				Files: []File{
					{Name: "opensearch.yml", Data: []byte(opensearchConfig(s))},
					{Name: "start.sh", Mode: 0o755, Data: []byte(opensearchStartScript(endpoint))},
				},
				Health: Health{
					// Verifies TLS against the lab CA, admin auth, and cluster readiness.
					Test: []string{
						"CMD-SHELL",
						fmt.Sprintf(`curl -sf -o /dev/null --cacert %s -u "admin:$$OPENSEARCH_PASSWORD" "%s"`, CAFile, healthURL),
					},
					Interval:      10 * time.Second,
					Timeout:       10 * time.Second,
					Retries:       10,
					StartPeriod:   60 * time.Second,
					StartInterval: 2 * time.Second,
				},
			}
		},
		Client: func(c Client) []EnvVar {
			return []EnvVar{
				{Name: "OPENSEARCH_URL", Value: fmt.Sprintf("https://%s:%d", c.FQDN, OpenSearchHTTPPort)},
				{Name: "OPENSEARCH_USER", Value: "admin"},
				{Name: "OPENSEARCH_PASSWORD", Value: c.Secret("password"), Secret: true},
				{Name: "OPENSEARCH_CACERT", Value: CAFile},
			}
		},
	}
}

func opensearchConfig(s Server) string {
	// Breadboard's PKI issues leaf certs with Subject "CN=<fqdn>,O=Breadboard"
	// (internal/pki/pki.go). Transport stays bound to 127.0.0.1 in single-node
	// mode and still requires TLS + node DN verification.
	nodeDN := fmt.Sprintf("CN=%s,O=Breadboard", s.FQDN)

	return strings.Join([]string{
		"# Generated by Breadboard for " + s.Name + ".",
		"cluster.name: " + s.Name,
		"node.name: " + s.Name,
		"discovery.type: single-node",
		"network.host: 0.0.0.0",
		"http.publish_host: " + s.FQDN,
		fmt.Sprintf("http.port: %d", OpenSearchHTTPPort),
		"transport.host: 127.0.0.1",
		fmt.Sprintf("transport.port: %d", OpenSearchTransportPort),
		"",
		"plugins.security.disabled: false",
		"plugins.security.allow_default_init_securityindex: true",
		"plugins.security.ssl.http.enabled: true",
		"plugins.security.ssl.http.pemcert_filepath: bb-certs/tls.crt",
		"plugins.security.ssl.http.pemkey_filepath: bb-certs/tls.key",
		"plugins.security.ssl.http.pemtrustedcas_filepath: bb-certs/ca.pem",
		"plugins.security.ssl.transport.pemcert_filepath: bb-certs/tls.crt",
		"plugins.security.ssl.transport.pemkey_filepath: bb-certs/tls.key",
		"plugins.security.ssl.transport.pemtrustedcas_filepath: bb-certs/ca.pem",
		"plugins.security.ssl.transport.enforce_hostname_verification: false",
		"plugins.security.nodes_dn:",
		fmt.Sprintf("  - %q", nodeDN),
		"plugins.security.authcz.admin_dn:",
		fmt.Sprintf("  - %q", nodeDN),
		"",
	}, "\n")
}

func opensearchStartScript(endpoint string) string {
	return strings.Join([]string{
		"#!/usr/bin/env bash",
		"set -euo pipefail",
		"",
		"CONF_DIR=/usr/share/opensearch/config",
		"CERT_DIR=\"$CONF_DIR/bb-certs\"",
		"mkdir -p \"$CERT_DIR\"",
		"cp " + CertFile + " \"$CERT_DIR/tls.crt\"",
		"cp " + KeyFile + " \"$CERT_DIR/tls.key\"",
		"cp " + CAFile + " \"$CERT_DIR/ca.pem\"",
		"chmod 600 \"$CERT_DIR/tls.key\"",
		"chmod 644 \"$CERT_DIR/tls.crt\" \"$CERT_DIR/ca.pem\"",
		"",
		"cp " + ConfigDir + "/opensearch.yml \"$CONF_DIR/opensearch.yml\"",
		"",
		"# Hash the Breadboard-generated admin password with OpenSearch's bundled bcrypt tool",
		"# so no default demo accounts or passwords exist.",
		"HASH=$(OPENSEARCH_JAVA_HOME=/usr/share/opensearch/jdk \\",
		"  /usr/share/opensearch/plugins/opensearch-security/tools/hash.sh -p \"$OPENSEARCH_PASSWORD\" | grep -E '^\\$2' | tail -n 1)",
		"if [ -z \"$HASH\" ]; then",
		"  echo 'failed to hash OpenSearch admin password' >&2",
		"  exit 1",
		"fi",
		"",
		"umask 077",
		"cat > \"$CONF_DIR/opensearch-security/internal_users.yml\" <<EOF",
		"---",
		"_meta:",
		"  type: \"internalusers\"",
		"  config_version: 2",
		"admin:",
		"  hash: \"$HASH\"",
		"  reserved: true",
		"  backend_roles:",
		"  - \"admin\"",
		"  description: \"Breadboard admin user\"",
		"EOF",
		"umask 022",
		"",
		"if [ -n \"${BB_INDICES:-}\" ]; then",
		"  (",
		"    IFS=','; for idx in $BB_INDICES; do",
		"      [ -z \"$idx\" ] && continue",
		fmt.Sprintf("      until curl -sf -o /dev/null --cacert %s -u \"admin:$OPENSEARCH_PASSWORD\" \"%s/_cluster/health?wait_for_status=yellow&timeout=2s\"; do sleep 1; done", CAFile, endpoint),
		fmt.Sprintf("      curl -sf -o /dev/null --cacert %s -u \"admin:$OPENSEARCH_PASSWORD\" -I \"%s/$idx\" || \\", CAFile, endpoint),
		fmt.Sprintf("        curl -sf -o /dev/null --cacert %s -u \"admin:$OPENSEARCH_PASSWORD\" -X PUT \"%s/$idx\" -H 'Content-Type: application/json' -d '{\"settings\":{\"number_of_shards\":1,\"number_of_replicas\":0}}'", CAFile, endpoint),
		"    done",
		"  ) &",
		"fi",
		"",
		"exec /usr/share/opensearch/opensearch-docker-entrypoint.sh opensearch",
		"",
	}, "\n")
}
