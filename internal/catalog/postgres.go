package catalog

import (
	"errors"
	"fmt"
	"regexp"
	"strconv"
	"strings"
	"time"
)

func postgres() *Entry {
	const port = 5432

	ident := regexp.MustCompile(`^[a-z_][a-z0-9_]{0,62}$`)
	identifier := func(v string) error {
		if !ident.MatchString(v) {
			return errors.New("must be a lowercase identifier (a-z, 0-9, _; at most 63 characters)")
		}

		return nil
	}

	return &Entry{
		ID:      "postgres",
		Title:   "Postgres",
		Summary: "PostgreSQL relational database with TLS required (verify-full).",
		Image:   "postgres:18.7-alpine3.24",
		Listeners: []Listener{
			{Name: "postgres", Protocol: "postgres", Port: port, PlaintextPort: port},
		},
		Resources: Resources{Memory: "512m", CPUs: "0.5"},
		Secrets: []Secret{
			{Key: "superuser-password", Kind: Password, Help: "password of the postgres superuser"},
			{Key: "password", Kind: Password, Help: "password of the application role"},
		},
		Config: []ConfigOption{
			{Key: "database", Default: "app", Help: "database created for apps", Validate: identifier},
			{Key: "user", Default: "app", Help: "application role apps connect as", Validate: func(v string) error {
				if v == "postgres" {
					return errors.New("must not be postgres; apps connect as their own role, not the superuser")
				}

				return identifier(v)
			}},
		},
		// Postgres 18 images keep data under a versioned subdirectory of this path.
		DataPath: "/var/lib/postgresql",
		Notes:    notes("postgres"),
		Server: func(s Server) Container {
			hba := []string{
				"# Generated by Breadboard.",
				"# TYPE    DATABASE USER ADDRESS METHOD",
				"# Unix socket inside the container only (init scripts, docker exec).",
				"local     all      all          trust",
				"# Every network connection must use TLS.",
				"hostssl   all      all  all     scram-sha-256",
			}
			if s.Plain != nil {
				hba = append(hba,
					"# Plaintext, only from the private segment shared with: "+strings.Join(s.Plain.Clients, ", "),
				)
				for _, r := range s.Plain.Reasons {
					hba = append(hba, hbaComment("Reason: "+r))
				}

				hba = append(hba, fmt.Sprintf("hostnossl all      all  %s scram-sha-256", s.Plain.Subnet))
			}

			initSQL := strings.Join([]string{
				"#!/bin/sh",
				"# Generated by Breadboard. Runs once, when the data directory is empty:",
				"# creates the application role and its database.",
				"set -eu",
				`psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres \`,
				`  -v app_user="$BB_APP_USER" -v app_password="$BB_APP_PASSWORD" -v app_db="$BB_APP_DATABASE" <<'SQL'`,
				`CREATE ROLE :"app_user" LOGIN PASSWORD :'app_password';`,
				`CREATE DATABASE :"app_db" OWNER :"app_user";`,
				"SQL",
			}, "\n") + "\n"
			// Postgres refuses a key that is readable by others or owned by
			// another user, so the mounted key is copied with the right owner
			// and mode before the server starts.
			start := strings.Join([]string{
				"set -e",
				"install -d -m 0700 -o postgres -g postgres /var/run/postgresql/bb-tls",
				"install -m 0600 -o postgres -g postgres " + KeyFile + " /var/run/postgresql/bb-tls/tls.key",
				"install -m 0644 -o postgres -g postgres " + CertFile + " /var/run/postgresql/bb-tls/tls.crt",
				"exec docker-entrypoint.sh postgres" +
					" -c listen_addresses='*'" +
					" -c ssl=on" +
					" -c ssl_cert_file=/var/run/postgresql/bb-tls/tls.crt" +
					" -c ssl_key_file=/var/run/postgresql/bb-tls/tls.key" +
					" -c ssl_min_protocol_version=TLSv1.2" +
					" -c hba_file=" + ConfigDir + "/pg_hba.conf",
			}, "\n")
			db, user := s.Config["database"], s.Config["user"]

			return Container{
				Entrypoint: []string{"/bin/sh", "-c", start},
				Environment: []EnvVar{
					{Name: "POSTGRES_USER", Value: "postgres"},
					{Name: "POSTGRES_PASSWORD", Value: s.Secret("superuser-password"), Secret: true},
					{Name: "BB_APP_USER", Value: user},
					{Name: "BB_APP_PASSWORD", Value: s.Secret("password"), Secret: true},
					{Name: "BB_APP_DATABASE", Value: db},
				},
				Files: []File{
					{Name: "pg_hba.conf", Data: []byte(strings.Join(hba, "\n") + "\n")},
					{Name: "init-app.sh", Mount: "/docker-entrypoint-initdb.d/10-init-app.sh", Data: []byte(initSQL), Mode: 0o755},
				},
				Health: Health{
					// A real query over TLS with verify-full against the FQDN.
					Test: []string{"CMD-SHELL", fmt.Sprintf(
						`PGPASSWORD="$$BB_APP_PASSWORD" psql "host=%s port=%d dbname=%s user=%s sslmode=verify-full sslrootcert=%s" -tAc 'select 1' > /dev/null`,
						s.FQDN, port, db, user, CAFile)},
					Interval:      10 * time.Second,
					Timeout:       5 * time.Second,
					Retries:       10,
					StartPeriod:   60 * time.Second,
					StartInterval: 2 * time.Second,
				},
			}
		},
		Client: func(c Client) []EnvVar {
			db, user := c.Config["database"], c.Config["user"]

			host, mode := c.FQDN, "verify-full"
			if c.Plain != nil {
				host, mode = c.Plain.FQDN, "disable"
			}

			pw := c.Secret("password")

			return []EnvVar{
				{Name: "DATABASE_URL", Value: fmt.Sprintf("postgres://%s:%s@%s:%d/%s?sslmode=%s", user, pw, host, port, db, mode), Secret: true},
				{Name: "PGHOST", Value: host},
				{Name: "PGPORT", Value: strconv.Itoa(port)},
				{Name: "PGUSER", Value: user},
				{Name: "PGPASSWORD", Value: pw, Secret: true},
				{Name: "PGDATABASE", Value: db},
				{Name: "PGSSLMODE", Value: mode},
				{Name: "PGSSLROOTCERT", Value: CAFile},
			}
		},
	}
}

// hbaComment renders user text (a tls.reason) as pg_hba.conf comment lines
// through Comment, so no line of it can become a record. pg_hba.conf joins a
// line ending in a backslash with the next one before it strips comments,
// so such a line gets a closing "#": the record after a comment can never
// be swallowed into it.
func hbaComment(text string) string {
	lines := strings.Split(Comment("# ", text), "\n")
	for i, l := range lines {
		if strings.HasSuffix(l, `\`) {
			lines[i] = l + "#"
		}
	}

	return strings.Join(lines, "\n")
}
