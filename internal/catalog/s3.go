package catalog

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
	"time"
)

func s3Compatible() *Entry {
	const (
		port   = 8333
		region = "us-east-1"
	)
	bucketName := regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$`)
	return &Entry{
		ID:      "s3-compatible",
		Title:   "S3 Compatible",
		Summary: "Object storage speaking the S3 API (SeaweedFS): HTTPS on 8333, generated access keys.",
		Image:   "chrislusf/seaweedfs:4.53",
		// SeaweedFS binds its S3 HTTPS port and its S3 gRPC port to the same
		// address, so a plaintext listener could not be confined to a segment.
		Listeners: []Listener{{Name: "s3", Protocol: "https", Port: port}},
		Resources: Resources{Memory: "512m", CPUs: "0.5"},
		Secrets: []Secret{
			{Key: "access-key-id", Kind: Password, Help: "S3 access key id of the admin identity"},
			{Key: "secret-access-key", Kind: Password, Help: "S3 secret access key of the admin identity"},
		},
		Config: []ConfigOption{
			{Key: "buckets", Default: "", Help: "comma-separated buckets created at startup", Validate: func(v string) error {
				if strings.Contains(v, " ") {
					return errors.New("separate buckets with commas, no spaces")
				}
				for _, b := range strings.Split(v, ",") {
					if b != "" && !bucketName.MatchString(b) {
						return fmt.Errorf("bucket %q: must be 3-63 characters of a-z, 0-9, '.' and '-'", b)
					}
				}
				return nil
			}},
		},
		DataPath: "/data",
		Notes:    notes("s3-compatible"),
		Server: func(s Server) Container {
			endpoint := fmt.Sprintf("https://%s:%d", s.FQDN, port)
			signed := fmt.Sprintf(`curl -sf -o /dev/null --cacert %s --aws-sigv4 aws:amz:%s:s3 --user "$$AWS_ACCESS_KEY_ID:$$AWS_SECRET_ACCESS_KEY"`, CAFile, region)
			// Master, volume and filer listen on loopback only; the S3 gateway
			// is the one network listener, HTTPS on 8333. Its gRPC port cannot
			// be disabled, so security.toml requires mutual TLS on every gRPC
			// port and accepts only this service's own certificate.
			weed := strings.Join([]string{
				"weed server -dir=/data -ip=127.0.0.1 -ip.bind=127.0.0.1",
				"-master.volumeSizeLimitMB=1024",
				"-s3 -s3.ip.bind=0.0.0.0", fmt.Sprintf("-s3.port=%d", port),
				"-s3.cert.file=" + CertFile, "-s3.key.file=" + KeyFile,
				"-s3.port.iceberg=0 -s3.port.lance=0",
			}, " ")
			// Configured buckets are created once the gateway answers; the
			// trap forwards docker stop to weed so it shuts down cleanly.
			start := strings.Join([]string{
				weed + " &",
				"pid=$$!",
				`trap 'kill -TERM $$pid; wait $$pid; exit' TERM INT`,
				`for b in $$(echo "$$BB_BUCKETS" | tr , ' '); do`,
				fmt.Sprintf(`  until %s -I %s/$$b || %s -X PUT %s/$$b; do sleep 1; done`, signed, endpoint, signed, endpoint),
				"done",
				"wait $$pid",
			}, "\n")
			sec := []string{"# Generated by Breadboard: mutual TLS on every SeaweedFS gRPC port.", "[grpc]", fmt.Sprintf("ca = %q", CAFile)}
			for _, c := range []string{"master", "volume", "filer", "s3", "client"} {
				sec = append(sec, "", "[grpc."+c+"]", fmt.Sprintf("cert = %q", CertFile), fmt.Sprintf("key = %q", KeyFile))
				if c != "client" {
					sec = append(sec, fmt.Sprintf("allowed_commonNames = %q", s.FQDN))
				}
			}
			return Container{
				Entrypoint: []string{"/bin/sh", "-c", start},
				Environment: []EnvVar{
					// SeaweedFS uses these as the admin identity when no IAM config exists.
					{Name: "AWS_ACCESS_KEY_ID", Value: s.Secret("access-key-id"), Secret: true},
					{Name: "AWS_SECRET_ACCESS_KEY", Value: s.Secret("secret-access-key"), Secret: true},
					{Name: "BB_BUCKETS", Value: s.Config["buckets"]},
				},
				Files: []File{{Name: "security.toml", Mount: "/etc/seaweedfs/security.toml", Data: []byte(strings.Join(sec, "\n") + "\n")}},
				Health: Health{
					// An authenticated ListBuckets over TLS, verified against the FQDN.
					Test:          []string{"CMD-SHELL", signed + " " + endpoint + "/"},
					Interval:      10 * time.Second,
					Timeout:       5 * time.Second,
					Retries:       5,
					StartPeriod:   30 * time.Second,
					StartInterval: 1 * time.Second,
				},
			}
		},
		Client: func(c Client) []EnvVar {
			endpoint := fmt.Sprintf("https://%s:%d", c.FQDN, port)
			id, secret := c.Secret("access-key-id"), c.Secret("secret-access-key")
			return []EnvVar{
				{Name: "S3_ENDPOINT", Value: endpoint},
				{Name: "S3_REGION", Value: region},
				{Name: "S3_ACCESS_KEY_ID", Value: id, Secret: true},
				{Name: "S3_SECRET_ACCESS_KEY", Value: secret, Secret: true},
				{Name: "S3_FORCE_PATH_STYLE", Value: "true"},
				// Read by the official AWS SDKs, so clients need no endpoint code.
				{Name: "AWS_ENDPOINT_URL_S3", Value: endpoint},
				{Name: "AWS_REGION", Value: region},
				{Name: "AWS_ACCESS_KEY_ID", Value: id, Secret: true},
				{Name: "AWS_SECRET_ACCESS_KEY", Value: secret, Secret: true},
			}
		},
	}
}
