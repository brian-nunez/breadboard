package sidecar

import (
	"fmt"
	"strconv"
	"strings"
	"time"

	"github.com/brian-nunez/breadboard/internal/catalog"
	"github.com/brian-nunez/breadboard/internal/spec"
)

// FluentBitUploadTimeout is how long Fluent Bit buffers a log file before
// uploading it as one object: short, so a lab shows its logs quickly.
const FluentBitUploadTimeout = "10s"

func renderFluentBit(in Input) (Output, error) {
	fb := in.Spec.FluentBit
	if fb == nil {
		return Output{}, fmt.Errorf("sidecar %s: no fluent-bit settings", in.Name)
	}

	use, ok := in.use(fb.To)
	if !ok {
		return Output{}, fmt.Errorf("sidecar %s: %s is not in the app's uses", in.Name, fb.To)
	}

	region := "us-east-1"

	for _, v := range use.Env {
		if strings.HasSuffix(v.Name, "S3_REGION") {
			region = v.Value
		}
	}

	endpoint := fmt.Sprintf("https://%s:%d", use.FQDN, use.Port)
	section := func(name string, kv ...string) []string {
		lines := []string{"[" + name + "]"}
		for i := 0; i+1 < len(kv); i += 2 {
			lines = append(lines, fmt.Sprintf("    %-20s %s", kv[i], kv[i+1]))
		}

		return append(lines, "")
	}
	conf := []string{
		"# Generated by Breadboard for " + in.Name + ": ships the log files " + in.App.Service + " writes",
		"# to " + LogDir + " to the bucket " + fb.Bucket + " on " + fb.To + ", over TLS verified against the lab CA.",
		"",
	}
	conf = append(conf, section("SERVICE",
		"Flush", "1",
		"Log_Level", "info",
		"HTTP_Server", "On",
		"HTTP_Listen", "127.0.0.1",
		"HTTP_Port", strconv.Itoa(spec.FluentBitHTTPPort),
		"Health_Check", "On",
	)...)
	conf = append(conf, section("INPUT",
		"Name", "tail",
		"Path", LogDir+"/*.log",
		"Tag", "logs."+in.App.Service,
		"Path_Key", "file",
		"Read_from_Head", "On",
		"Refresh_Interval", "2",
		// Offsets live in the shared directory, so a restarted Fluent Bit
		// does not ship the same lines twice.
		"DB", SharedDir+"/fluent-bit-"+in.App.Service+".db",
	)...)
	conf = append(conf, section("OUTPUT",
		"Name", "s3",
		"Match", "logs.*",
		"bucket", fb.Bucket,
		"region", region,
		"endpoint", endpoint,
		"tls.verify", "On",
		"tls.verify_hostname", "On",
		"tls.ca_file", catalog.CAFile,
		"use_put_object", "On",
		"total_file_size", "1M",
		"upload_timeout", FluentBitUploadTimeout,
		"s3_key_format", "/"+in.App.Service+"/%Y/%m/%d/%H%M%S-$UUID.jsonl",
		"store_dir", "/tmp/fluent-bit/s3",
	)...)
	start := strings.Join([]string{
		"set -e",
		// The app may run as any user: the log directory is writable by all,
		// like /tmp.
		"mkdir -p " + LogDir,
		"chmod 1777 " + LogDir,
		"exec /fluent-bit/bin/fluent-bit -c " + catalog.ConfigDir + "/fluent-bit.conf",
	}, "\n")

	return Output{
		Container: catalog.Container{
			Entrypoint: []string{"/bin/sh", "-c", start},
			Environment: []catalog.EnvVar{
				// Read by Fluent Bit's AWS credential chain.
				{Name: "AWS_ACCESS_KEY_ID", Value: in.Secret(fb.To)("access-key-id"), Secret: true},
				{Name: "AWS_SECRET_ACCESS_KEY", Value: in.Secret(fb.To)("secret-access-key"), Secret: true},
			},
			Files: []catalog.File{{Name: "fluent-bit.conf", Data: []byte(strings.Join(conf, "\n"))}},
			Health: catalog.Health{
				Test:          []string{"CMD", "bash", "-c", httpCheck(spec.FluentBitHTTPPort, "/api/v1/health")},
				Interval:      10 * time.Second,
				Timeout:       3 * time.Second,
				Retries:       3,
				StartPeriod:   20 * time.Second,
				StartInterval: 1 * time.Second,
			},
		},
		AppEnv: []catalog.EnvVar{{Name: "BB_LOG_DIR", Value: LogDir}},
		Needs:  []string{fb.To},
	}, nil
}
