// Traefik as an infra proxy, configured by the file provider only: it never
// sees the Docker socket. The static config (entrypoints, the provider,
// ping, the API) is Breadboard's; the dynamic config (routers, middlewares,
// services, transports) is what file replaces.
const (
	// TraefikAPIPort is the loopback-only entrypoint "traefik": the API and
	// dashboard (for explorers, through docker exec) and /ping (for the
	// health check). Nothing outside the container reaches it.
	TraefikAPIPort = 8080
	// traefikConfigFile is the dynamic config, the file a spec's file
	// replaces; traefikTLSFile holds the certificate store. Both are read
	// from traefikDynamicDir by the file provider.
	traefikConfigFile = "dynamic.yml"
	traefikTLSFile    = "tls.yml"
	traefikStaticFile = "traefik.yml"
	traefikDynamicDir = "/etc/bb/traefik"
	traefikEntrypoint = "websecure"
	traefikPassEntry  = "passthrough"
	traefikAPIEntry   = "traefik"
	traefikTLSPrefix  = "tls-"
	// Generated HTTP routers live in disjoint namespaces, so no route name
	// can collide with another router: route-<route> for each upstream's
	// route, default-<first> for the fallback with several upstreams.
	traefikRoutePrefix   = "route-"
	traefikDefaultPrefix = "default-"
)

func traefik() *Entry {
	return &Entry{
		ID:        "traefik",
		Title:     "Traefik",
		Summary:   "Traefik router and load balancer from a file provider: TLS on 8443, path routing, health checks, re-encrypt, terminate and SNI passthrough.",
		Image:     "traefik:v3.7.19",
		Listeners: HTTPProxyListeners(),
		Resources: Resources{Memory: "128m", CPUs: "0.25"},
		Notes:     notes("traefik"),
		Proxy: &Proxy{
			Modes:       []string{spec.TLSOn, spec.TLSOff, spec.TLSPassthrough},
			HTTP:        true,
			ConfigFile:  traefikConfigFile,
			StaticFile:  traefikStaticFile,
			MergeStatic: traefikMergeStatic,
			Unit:        traefikService,
		},
		Server: func(s Server) Container {
			return traefikContainer(traefikStaticConfig(s), traefikTLSConfig(s), traefikDynamicConfig(s))
		},
		Client: ProxyClientEnv,
	}
}

// traefikContainer runs Traefik on the three generated files: the static
// config, the certificate store and the routes, both read by the file
// provider from traefikDynamicDir.
func traefikContainer(static, tls, dynamic []byte) Container {
	staticPath := ConfigDir + "/" + traefikStaticFile
	return Container{
		Command: []string{"traefik", "--configFile=" + staticPath},
		Files: []File{
			{Name: traefikStaticFile, Data: static},
			{Name: traefikTLSFile, Mount: traefikDynamicDir + "/" + traefikTLSFile, Data: tls},
			{Name: traefikConfigFile, Mount: traefikDynamicDir + "/" + traefikConfigFile, Data: dynamic},
		},
		Health: Health{
			// The image is Alpine without curl or openssl; Traefik's
			// own client asks /ping on the loopback entrypoint the
			// static config names.
			Test:          []string{"CMD", "traefik", "healthcheck", "--configFile=" + staticPath, "--ping"},
			Interval:      10 * time.Second,
			Timeout:       5 * time.Second,
			Retries:       3,
			StartPeriod:   30 * time.Second,
			StartInterval: 1 * time.Second,
		},
	}
}

// traefikStaticConfig is the install configuration: entrypoints, the file
// provider, ping and the API on loopback.
func traefikStaticConfig(s Server) []byte {
	return encodeYAMLDoc(traefikStaticHeader(s), traefikStaticDoc(s, "this service's certificate"))
}

func traefikStaticHeader(s Server) []string {
	return []string{
		fmt.Sprintf("traefik.yml for %s, generated by Breadboard: the static (install)", s.Name),
		"configuration. Breadboard owns it, because its health check and",
		"listeners depend on it. Routing lives in the dynamic configuration",
		fmt.Sprintf("in %s, which services.%s.file replaces.", traefikDynamicDir, s.Name),
	}
}

// traefikEncodedCharacters denies every encoded character Traefik v3.7 can
// filter in a request path, on each entry point (D-204). Traefik allows all
// seven by default since v3.6.7 and logs a startup warning until an entry
// point denies one.
func traefikEncodedCharacters() ymap {
	return ym(
		"allowEncodedSlash", false,
		"allowEncodedBackSlash", false,
		"allowEncodedNullCharacter", false,
		"allowEncodedSemicolon", false,
		"allowEncodedPercent", false,
		"allowEncodedQuestionMark", false,
		"allowEncodedHash", false,
	)
}

// traefikStaticDoc is the static configuration's document; cert names the
// certificate the HTTPS entrypoint presents, for its comment.
func traefikStaticDoc(s Server, cert string) ymap {
	entrypoints := ym(
		ycomment(fmt.Sprintf("HTTPS with %s (the default certificate in\n%s/%s). Routers on it use TLS without saying so.", cert, traefikDynamicDir, traefikTLSFile)),
		traefikEntrypoint, ym(
			"address", fmt.Sprintf(":%d", ProxyHTTPSPort),
			"http", ym(
				"tls", ym(),
				ycomment("Drop request headers whose names alias a header Traefik manages\n(X_Forwarded_For for X-Forwarded-For), so clients cannot spoof them."),
				"aliasHeadersStrategy", "delete",
				ycomment("Reject (400) a request path holding an encoded /, \\, NUL, ;, %, ?\nor #. A backend that decodes the path again could route it apart\nfrom Traefik's rules (a split view), e.g. /api%2F..%2Fadmin. Traefik\nallows them by default and warns at startup until one is denied."),
				"encodedCharacters", traefikEncodedCharacters(),
			),
		),
	)
	if len(Passthroughs(s.Upstreams)) > 0 {
		entrypoints = append(entrypoints, yfield{
			key:     traefikPassEntry,
			comment: "TLS routed by SNI without decrypting: TCP routers with passthrough.",
			value:   ym("address", fmt.Sprintf(":%d", ProxyPassthroughPort), "http", ym("aliasHeadersStrategy", "delete", "encodedCharacters", traefikEncodedCharacters())),
		})
	}
	entrypoints = append(entrypoints, yfield{
		key:     traefikAPIEntry,
		comment: "Loopback only: the API, the dashboard and /ping.",
		value:   ym("address", fmt.Sprintf("127.0.0.1:%d", TraefikAPIPort), "http", ym("aliasHeadersStrategy", "delete", "encodedCharacters", traefikEncodedCharacters())),
	})
	doc := ym(
		"global", ym("checkNewVersion", false, "sendAnonymousUsage", false),
		ycomment("Logs and access logs go to stdout: bb logs "+s.Name+"."),
		"log", ym("level", "INFO"),
		"accessLog", ym(),
		"entryPoints", entrypoints,
		ycomment("The file provider only; Traefik never sees the Docker socket. Every\nfile in the directory is loaded and watched for changes."),
		"providers", ym("file", ym("directory", traefikDynamicDir, "watch", true)),
		ycomment(fmt.Sprintf("The API and dashboard on the %s entrypoint (127.0.0.1:%d).", traefikAPIEntry, TraefikAPIPort)),
		"api", ym("insecure", true, "dashboard", true),
		"ping", ym("entryPoint", traefikAPIEntry),
	)
	return doc
}

// traefikService is the Traefik service (HTTP, or TCP for passthrough)
// that balances an upstream.
func traefikService(u Upstream) string {
	if u.Passthrough() {
		return traefikTLSPrefix + u.Name
	}
	return u.Name
}

// traefikTLSConfig is the certificate store and TLS options: dynamic
// configuration Breadboard keeps beside the user's routes.
func traefikTLSConfig(s Server) []byte {
	header := []string{
		fmt.Sprintf("tls.yml for %s, generated by Breadboard: the certificate Traefik", s.Name),
		"presents and the minimum TLS version. It stays when services." + s.Name + ".file",
		"replaces the routes in " + traefikConfigFile + ".",
	}
	doc := ym("tls", ym(
		"stores", ym("default", ym("defaultCertificate", ym("certFile", CertFile, "keyFile", KeyFile))),
		ycomment("TLS 1.2 or newer towards clients."),
		"options", ym("default", ym("minVersion", "VersionTLS12")),
	))
	return encodeYAMLDoc(header, doc)
}

// traefikDynamicConfig is the routing configuration: routers, middlewares,
// services and transports for every upstream.
func traefikDynamicConfig(s Server) []byte {
	l7, pass := L7(s.Upstreams), Passthroughs(s.Upstreams)
	header := []string{fmt.Sprintf("%s for %s, generated by Breadboard: the dynamic (routing)", traefikConfigFile, s.Name), "configuration.", ""}
	header = append(header, proxyRouteSummary(s.Upstreams)...)
	header = append(header, "",
		"To own it, copy it next to experiment.yaml and set services."+s.Name+".file.",
		fmt.Sprintf("The lab CA (%s) stays mounted, and Breadboard keeps the", CAFile),
		fmt.Sprintf("entrypoints (%s on :%d, and %s on :%d with a", traefikEntrypoint, ProxyHTTPSPort, traefikPassEntry, ProxyPassthroughPort),
		"passthrough upstream) and the certificate store in "+traefikTLSFile+".",
		"",
		"Each app replica is listed by name: Traefik does not discover the",
		"several addresses of one DNS name.",
	)

	routers, middlewares, services, transports := ym(), ym(), ym(), ym()
	router := func(name, rule, service, comment string, mws ...string) {
		r := ym("entryPoints", yseq{traefikEntrypoint}, "rule", rule, "service", service)
		if len(mws) > 0 {
			r = append(r, yfield{key: "middlewares", value: mws})
		}
		routers = append(routers, yfield{key: name, value: r, comment: comment})
	}
	switch len(l7) {
	case 0:
		router("no-upstream", "PathPrefix(`/`)", "no-upstream", "No upstream yet: a service without servers answers 503.")
		services = append(services, yfield{key: "no-upstream", value: ym("loadBalancer", ym("servers", yseq{}))})
	case 1:
		router(traefikRoutePrefix+l7[0].Name, "PathPrefix(`/`)", l7[0].Name, "Every request goes to "+l7[0].Service+".")
	default:
		for _, u := range l7 {
			mw := "strip-" + u.Name
			router(traefikRoutePrefix+u.Name, "PathPrefix(`"+u.Prefix()+"`)", u.Name,
				fmt.Sprintf("%s goes to %s with the prefix stripped.", u.Prefix(), u.Service), mw)
			middlewares = append(middlewares, yfield{key: mw, value: ym("stripPrefix", ym("prefixes", yseq{strings.TrimSuffix(u.Prefix(), "/")}))})
		}
		router(traefikDefaultPrefix+l7[0].Name, "PathPrefix(`/`)", l7[0].Name,
			"Every other path goes to the first upstream: by default a longer rule\nhas a higher priority, so the prefixes above win.")
	}
	for _, u := range l7 {
		var servers yseq
		for _, host := range u.Servers {
			scheme := "https"
			if u.Mode == spec.TLSOff {
				scheme = "http"
			}
			servers = append(servers, ym("url", fmt.Sprintf("%s://%s:%d", scheme, host, u.Port)))
		}
		lb := ym(
			ycomment("Weighted round robin. Other strategies: p2c (power of two choices),\nhrw (highest random weight) and leasttime."),
			"strategy", "wrr",
			"servers", servers,
		)
		if u.App {
			lb = append(lb, yfield{key: "healthCheck", comment: "Active checks every 2s: a 2xx or 3xx answer keeps a server in the\nrotation. Point path at your app's health endpoint in your own copy.", value: ym(
				"path", "/",
				"hostname", u.ServerName,
				"interval", "2s",
				"timeout", "2s",
			)})
		}
		if u.Mode == spec.TLSOn {
			lb = append(lb, yfield{key: "serversTransport", value: u.Name})
			transports = append(transports, yfield{key: u.Name, comment: fmt.Sprintf("Re-encrypt: TLS with SNI %s, verified against the lab CA.", u.ServerName), value: ym(
				"serverName", u.ServerName,
				"rootCAs", yseq{CAFile},
			)})
		}
		services = append(services, yfield{key: u.Name, comment: proxyModeComment(u), value: ym("loadBalancer", lb)})
	}
	http := ym("routers", routers)
	if len(middlewares) > 0 {
		http = append(http, yfield{key: "middlewares", value: middlewares})
	}
	http = append(http, yfield{key: "services", value: services})
	if len(transports) > 0 {
		http = append(http, yfield{key: "serversTransports", value: transports})
	}
	doc := ym("http", http)

	if len(pass) > 0 {
		tcpRouters, tcpServices := ym(), ym()
		for _, u := range pass {
			name := traefikService(u)
			tcpRouters = append(tcpRouters, yfield{key: name, comment: "SNI " + u.ServerName + " goes to " + u.Service + " still encrypted.", value: ym(
				"entryPoints", yseq{traefikPassEntry},
				"rule", "HostSNI(`"+u.ServerName+"`)",
				"service", name,
				"tls", ym("passthrough", true),
			)})
			var servers yseq
			for _, host := range u.Servers {
				servers = append(servers, ym("address", fmt.Sprintf("%s:%d", host, u.Port)))
			}
			tcpServices = append(tcpServices, yfield{key: name, comment: proxyModeComment(u), value: ym("loadBalancer", ym(
				"servers", servers,
				ycomment("A TCP connect every 2s."),
				"healthCheck", ym("interval", "2s", "timeout", "2s"),
			))})
		}
		doc = append(doc, yfield{
			key:     "tcp",
			comment: "Passthrough: a name no router claims is closed.",
			value:   ym("routers", tcpRouters, "services", tcpServices),
		})
	}
	return traefikLiteral(encodeYAMLDoc(header, doc))
}

// traefikLiteral protects generated dynamic configuration from the file
// provider, which runs the whole file, comments included, through Go's
// text/template before decoding the YAML. Every "{{" in it (a reason may
// hold one) becomes the action {{"{{"}}, which the template pass turns
// back into the literal "{{"; a lone "}}" is already literal. A user's
// file is not generated here, so its own templates still run.
func traefikLiteral(b []byte) []byte {
	return bytes.ReplaceAll(b, []byte("{{"), []byte(`{{"{{"}}`))
}
