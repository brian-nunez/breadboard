// Sidecar explorers read a running sidecar's own view, like the infra
// explorers (ADR-0012): the sidecar's tool runs inside its container and
// the core parses what it prints.

// exploreSidecar resolves a sidecar of a type from a sidecar service name
// (api-2-envoy), an app instance (api-2: its first sidecar of the type), or
// an app (api: its first instance), and returns the sidecar, its app
// instance, the model, and a function that runs a command in the sidecar.
func (e *Engine) exploreSidecar(ctx context.Context, req ExploreRequest, typ string) (*model.Model, *model.Service, *model.Service, func(...string) ([]byte, error), error) {
	if err := e.rt.Available(ctx); err != nil {
		return nil, nil, nil, nil, err
	}

	p, err := e.open(req.Dir)
	if err != nil {
		return nil, nil, nil, nil, err
	}

	st, err := e.settings(ctx)
	if err != nil {
		return nil, nil, nil, nil, err
	}

	m, err := model.Resolve(p.spec, st.Domain)
	if err != nil {
		return nil, nil, nil, nil, err
	}

	sc, inst := findSidecar(m, req.Service, typ)
	if sc == nil {
		return nil, nil, nil, nil, fmt.Errorf("no %s sidecar for %q: %w", typ, req.Service, ErrNotFound)
	}

	run := func(cmd ...string) ([]byte, error) {
		return e.rt.Exec(ctx, m.Name, sc.Name, cmd)
	}

	return m, sc, inst, run, nil
}

func findSidecar(m *model.Model, name, typ string) (sc, inst *model.Service) {
	isType := func(s *model.Service) bool {
		return s.Kind == model.Sidecar && s.SidecarType != nil && s.SidecarType.ID == typ
	}

	svc, ok := m.Service(name)
	if !ok {
		if insts := m.Instances(name); len(insts) > 0 {
			svc, ok = insts[0], true
		}
	}

	switch {
	case !ok:
		return nil, nil
	case isType(svc):
		parent, _ := m.Service(svc.Parent)

		return svc, parent
	case svc.Kind == model.App:
		for _, n := range svc.Sidecars {
			if s, ok := m.Service(n); ok && isType(s) {
				return s, svc
			}
		}
	}

	return nil, nil
}

// --- Envoy ------------------------------------------------------------------

// EnvoyClusters is what an Envoy sidecar, or an infra Envoy proxy, knows
// about where it sends traffic.
type EnvoyClusters struct {
	Sidecar string // the sidecar's service name, e.g. caller-envoy
	App     string // the app instance it serves
	// Proxy is the infra Envoy service's name; Sidecar and App are empty
	// then.
	Proxy     string
	Listeners []EnvoyListener
	Clusters  []EnvoyCluster
}

// EnvoyListener is one address the sidecar accepts connections on.
type EnvoyListener struct {
	Name    string
	Address string // host:port
}

// EnvoyCluster is one upstream group and its hosts.
type EnvoyCluster struct {
	Name string
	// Role is what the cluster is for: outbound (to Target over TLS),
	// inbound (to the app on loopback), egress (transparent passthrough
	// to original destinations), or inbound passthrough (transparent); for
	// an infra proxy, upstream.
	Role   string
	Target string // the app or service it reaches, when known
	// Mode is an infra proxy's upstream TLS mode: spec.TLSOn, spec.TLSOff
	// or spec.TLSPassthrough.
	Mode string
	// Counters over the whole cluster.
	Retries           int64 // upstream_rq_retry
	EjectionsActive   int64 // hosts ejected by outlier detection right now
	EjectionsEnforced int64 // ejections ever enforced
	EjectionsOverflow int64 // ejections max_ejection_percent prevented
	Hosts             []EnvoyHost
}

// EnvoyHost is one upstream address with its health and counters.
type EnvoyHost struct {
	Address  string // ip:port
	Hostname string // the DNS name Envoy resolved, if any
	// Instance is the app instance or service at this address, from DNS
	// inside the sidecar: which replica a request went to.
	Instance string
	Healthy  bool
	// Flags are why a host is not healthy: failed_outlier_check (ejected),
	// failed_active_health_check, eds_unhealthy, ...
	Flags             []string
	Ejected           bool
	Requests          int64 // rq_total
	Successes         int64 // rq_success
	Errors            int64 // rq_error: 5xx and resets
	Timeouts          int64 // rq_timeout
	ConnectFailures   int64 // cx_connect_fail
	ActiveConnections int64 // cx_active
	ActiveRequests    int64 // rq_active
}

// Cluster names generated by internal/catalog/sidecar/envoy.go.
const (
	envoyOutboundPrefix        = "outbound_"
	envoyAppCluster            = "app"
	envoyPassthrough           = "passthrough"
	envoyInboundOrigDstCluster = "inbound_passthrough"
)

// envoyAdminScript reads the admin API (spec.EnvoyAdminPort) over bash's
// /dev/tcp (the image has no curl), then resolves the names given as
// arguments with the sidecar's own resolver, so host addresses map to
// instances.
const envoyAdminScript = `get() { exec 3<>/dev/tcp/127.0.0.1/15000 && printf 'GET %s HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n' "$1" >&3 && cat <&3; exec 3<&-; }
echo '### clusters'; get '/clusters?format=json'; echo
echo '### stats'; get '/stats?filter=^cluster\.[^.]+\.(upstream_rq_retry|outlier_detection\.ejections_(active|enforced_total|overflow))$'; echo
echo '### listeners'; get '/listeners?format=json'; echo
echo '### hosts'; [ $# -eq 0 ] || getent hosts "$@" || true`

// EnvoyClusters reads an Envoy's clusters, per-host health and counters,
// and listeners from its admin API on 127.0.0.1:15000. It takes an infra
// envoy service, or a sidecar as exploreSidecar finds one.
func (e *Engine) EnvoyClusters(ctx context.Context, req ExploreRequest) (*EnvoyClusters, error) {
	if m, svc, run, ok, err := e.infraProxy(ctx, req, "envoy"); err != nil || ok {
		if err != nil {
			return nil, err
		}

		return e.envoyInfra(m, svc, run)
	}

	m, sc, inst, run, err := e.exploreSidecar(ctx, req, spec.SidecarEnvoy)
	if err != nil {
		return nil, err
	}
	// The names whose addresses Envoy may connect to: every instance of an
	// app target, or a service's name.
	var names []string

	for _, t := range sc.Targets {
		if insts := m.Instances(t.Service); len(insts) > 0 {
			for _, i := range insts {
				names = append(names, i.FQDN)
			}
		} else if svc, ok := m.Service(t.Service); ok {
			names = append(names, svc.FQDN)
		}
	}

	out, err := run(append([]string{"bash", "-c", envoyAdminScript, "bb-envoy"}, names...)...)
	if err != nil {
		return nil, err
	}

	res, err := parseEnvoy(string(out), "."+m.Domain)
	if err != nil {
		return nil, err
	}

	res.Sidecar, res.App = sc.Name, inst.Name
	for i := range res.Clusters {
		c := &res.Clusters[i]
		switch {
		case strings.HasPrefix(c.Name, envoyOutboundPrefix):
			c.Role, c.Target = "outbound", strings.TrimPrefix(c.Name, envoyOutboundPrefix)
		case c.Name == envoyAppCluster:
			c.Role, c.Target = "inbound", inst.Group()
		case c.Name == envoyPassthrough:
			c.Role = "egress"
		case c.Name == envoyInboundOrigDstCluster:
			c.Role, c.Target = "inbound passthrough", inst.Group()
		}

		for j := range c.Hosts {
			if c.Hosts[j].Instance == "" && strings.HasPrefix(c.Hosts[j].Address, "127.0.0.1:") {
				c.Hosts[j].Instance = inst.Name // the app, on loopback
			}
		}
	}

	return res, nil
}

// parseEnvoy parses envoyAdminScript's output. suffix (".<domain>") is cut
// from resolved names to give instance names.
func parseEnvoy(out, suffix string) (*EnvoyClusters, error) {
	sections := splitSections(out)

	body, err := httpBody(sections["clusters"])
	if err != nil {
		return nil, fmt.Errorf("envoy /clusters: %w", err)
	}

	var cj struct {
		ClusterStatuses []struct {
			Name         string `json:"name"`
			HostStatuses []struct {
				Address      envoyAddress               `json:"address"`
				Stats        []envoyHostStat            `json:"stats"`
				HealthStatus map[string]json.RawMessage `json:"health_status"`
				Hostname     string                     `json:"hostname"`
			} `json:"host_statuses"`
		} `json:"cluster_statuses"`
	}
	if err := json.Unmarshal(body, &cj); err != nil {
		return nil, fmt.Errorf("envoy /clusters: %w", err)
	}

	hosts := map[string]string{}

	for _, line := range strings.Split(sections["hosts"], "\n") {
		if f := strings.Fields(line); len(f) >= 2 {
			hosts[f[0]] = strings.TrimSuffix(f[1], suffix)
		}
	}

	stats := map[string]int64{}

	if b, err := httpBody(sections["stats"]); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			k, v, ok := strings.Cut(strings.TrimSpace(line), ": ")
			if n, err := strconv.ParseInt(v, 10, 64); ok && err == nil {
				stats[k] = n
			}
		}
	}

	res := &EnvoyClusters{}

	for _, c := range cj.ClusterStatuses {
		cl := EnvoyCluster{
			Name:              c.Name,
			Retries:           stats["cluster."+c.Name+".upstream_rq_retry"],
			EjectionsActive:   stats["cluster."+c.Name+".outlier_detection.ejections_active"],
			EjectionsEnforced: stats["cluster."+c.Name+".outlier_detection.ejections_enforced_total"],
			EjectionsOverflow: stats["cluster."+c.Name+".outlier_detection.ejections_overflow"],
		}
		for _, h := range c.HostStatuses {
			host := EnvoyHost{
				Address:  h.Address.String(),
				Hostname: h.Hostname,
				Instance: hosts[h.Address.SocketAddress.Address],
			}
			for _, s := range h.Stats {
				n, _ := strconv.ParseInt(s.Value, 10, 64)
				switch s.Name {
				case "rq_total":
					host.Requests = n
				case "rq_success":
					host.Successes = n
				case "rq_error":
					host.Errors = n
				case "rq_timeout":
					host.Timeouts = n
				case "cx_connect_fail":
					host.ConnectFailures = n
				case "cx_active":
					host.ActiveConnections = n
				case "rq_active":
					host.ActiveRequests = n
				}
			}

			host.Flags = healthFlags(h.HealthStatus)
			host.Healthy = len(host.Flags) == 0
			host.Ejected = slices.Contains(host.Flags, "failed_outlier_check")
			cl.Hosts = append(cl.Hosts, host)
		}

		slices.SortStableFunc(cl.Hosts, func(a, b EnvoyHost) int {
			return cmp.Or(cmp.Compare(a.Instance, b.Instance), cmp.Compare(a.Address, b.Address))
		})
		res.Clusters = append(res.Clusters, cl)
	}

	if b, err := httpBody(sections["listeners"]); err == nil {
		var lj struct {
			ListenerStatuses []struct {
				Name         string       `json:"name"`
				LocalAddress envoyAddress `json:"local_address"`
			} `json:"listener_statuses"`
		}
		if err := json.Unmarshal(b, &lj); err != nil {
			return nil, fmt.Errorf("envoy /listeners: %w", err)
		}

		for _, l := range lj.ListenerStatuses {
			res.Listeners = append(res.Listeners, EnvoyListener{Name: l.Name, Address: l.LocalAddress.String()})
		}
	}

	return res, nil
}

type envoyAddress struct {
	SocketAddress struct {
		Address   string `json:"address"`
		PortValue int    `json:"port_value"`
	} `json:"socket_address"`
}

func (a envoyAddress) String() string {
	return fmt.Sprintf("%s:%d", a.SocketAddress.Address, a.SocketAddress.PortValue)
}

// envoyHostStat is a host counter; proto3 JSON writes 64-bit values as
// strings and leaves zeros out.
type envoyHostStat struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

// healthFlags lists why a host is not healthy: every flag Envoy set, and
// the discovery status when it is not HEALTHY.
func healthFlags(status map[string]json.RawMessage) []string {
	var flags []string

	for k, raw := range status {
		if k == "eds_health_status" {
			var s string
			if json.Unmarshal(raw, &s) == nil && s != "" && s != "HEALTHY" {
				flags = append(flags, "eds_"+strings.ToLower(s))
			}

			continue
		}

		var b bool
		if json.Unmarshal(raw, &b) == nil && b {
			flags = append(flags, k)
		}
	}

	slices.Sort(flags)

	return flags
}

// httpBody parses a raw HTTP/1.1 response (as read from /dev/tcp) and
// returns its body, chunked encoding undone. Framing lines (status,
// headers, chunk sizes, chunk ends) may end in CRLF, as Envoy sends them,
// or in a bare LF, as they read after a checkout normalised line endings;
// chunk data is taken by its declared size either way.
func httpBody(raw string) ([]byte, error) {
	r := bufio.NewReader(strings.NewReader(strings.TrimLeft(raw, "\r\n")))
	line := func() (string, error) {
		l, err := r.ReadString('\n')
		if err != nil && (err != io.EOF || l == "") {
			return "", err
		}

		return strings.TrimSuffix(strings.TrimSuffix(l, "\n"), "\r"), nil
	}

	statusLine, err := line()
	if err != nil {
		return nil, errors.New("no response")
	}

	proto, status, ok := strings.Cut(statusLine, " ")
	if !ok || !strings.HasPrefix(proto, "HTTP/") {
		return nil, fmt.Errorf("not an HTTP response: %q", statusLine)
	}

	code, _, _ := strings.Cut(status, " ")
	chunked, length := false, -1

	for {
		h, err := line()
		if err != nil {
			return nil, fmt.Errorf("headers: %w", err)
		}

		if h == "" {
			break
		}

		k, v, _ := strings.Cut(h, ":")
		switch strings.ToLower(strings.TrimSpace(k)) {
		case "transfer-encoding":
			chunked = strings.EqualFold(strings.TrimSpace(v), "chunked")
		case "content-length":
			length, _ = strconv.Atoi(strings.TrimSpace(v))
		}
	}

	var body []byte

	switch {
	case chunked:
		for {
			sz, err := line()
			if err != nil {
				return nil, fmt.Errorf("chunk size: %w", err)
			}

			sz, _, _ = strings.Cut(sz, ";") // chunk extensions

			n, err := strconv.ParseInt(strings.TrimSpace(sz), 16, 64)
			if err != nil || n < 0 {
				return nil, fmt.Errorf("chunk size %q", sz)
			}

			if n == 0 {
				break
			}

			chunk := make([]byte, n)
			if _, err := io.ReadFull(r, chunk); err != nil {
				return nil, fmt.Errorf("chunk: %w", err)
			}

			body = append(body, chunk...)

			if end, err := line(); err != nil || end != "" {
				return nil, fmt.Errorf("chunk of %d bytes not followed by a line end", n)
			}
		}
	case length >= 0:
		body = make([]byte, length)
		if _, err := io.ReadFull(r, body); err != nil {
			return nil, fmt.Errorf("body: %w", err)
		}
	default:
		if body, err = io.ReadAll(r); err != nil {
			return nil, err
		}
	}

	if code != "200" {
		return nil, fmt.Errorf("%s: %s", status, strings.TrimSpace(string(body)))
	}

	return body, nil
}

// --- PgBouncer --------------------------------------------------------------

// PgBouncerPools is a PgBouncer sidecar's, or an infra PgBouncer's,
// pools and traffic.
type PgBouncerPools struct {
	Sidecar string // the sidecar's service name, e.g. api-pgbouncer
	App     string // the app instance it serves
	// Proxy is the infra pgbouncer service's name, shared by every app
	// that uses it; Sidecar and App are empty then.
	Proxy    string
	Service  string // the Postgres service it pools
	PoolMode string
	PoolSize int
	Port     int // where apps reach it: on 127.0.0.1 for a sidecar
	Pools    []PgBouncerPool
}

// PgBouncerPool is one database/user pool (SHOW POOLS) with its
// database's totals (SHOW STATS).
type PgBouncerPool struct {
	Database string
	User     string
	PoolMode string
	// Client connections from the app: linked to a server connection, or
	// waiting for one.
	ClientsActive  int64
	ClientsWaiting int64
	// Server connections to Postgres: in use, idle and ready, idle but
	// needing a reset, and logging in.
	ServersActive int64
	ServersIdle   int64
	ServersUsed   int64
	ServersLogin  int64
	// MaxWaitMicros is how long the oldest waiting client has waited.
	MaxWaitMicros int64
	// Totals since PgBouncer started.
	Transactions   int64
	Queries        int64
	BytesReceived  int64
	BytesSent      int64
	AvgQueryMicros int64 // average query time over the last stats period
	AvgWaitMicros  int64 // average time clients waited for a server
}

// pgbouncerScript runs SHOW POOLS and SHOW STATS on the admin console as
// the app's role, whose password the sidecar already holds in its
// environment, so no secret crosses the exec boundary.
const pgbouncerScript = `q() { PGPASSWORD="$BB_PG_PASSWORD" psql -X -h 127.0.0.1 -p "$1" -U "$BB_PG_USER" -d pgbouncer -A -F "$(printf '\t')" -P footer=off -c "$2"; }
echo '### pools'; q "$1" 'SHOW POOLS'
echo '### stats'; q "$1" 'SHOW STATS'`

// PgBouncerPools reads a PgBouncer's pools with psql inside it: an infra
// pgbouncer service, or a sidecar as exploreSidecar finds one.
func (e *Engine) PgBouncerPools(ctx context.Context, req ExploreRequest) (*PgBouncerPools, error) {
	if _, svc, run, ok, err := e.infraProxy(ctx, req, "pgbouncer"); err != nil || ok {
		if err != nil {
			return nil, err
		}

		return e.pgbouncerInfra(svc, run)
	}

	_, sc, inst, run, err := e.exploreSidecar(ctx, req, spec.SidecarPgBouncer)
	if err != nil {
		return nil, err
	}

	pb := sc.Sidecar.PgBouncer

	out, err := run("sh", "-c", pgbouncerScript, "bb-pgbouncer", strconv.Itoa(pb.Port))
	if err != nil {
		return nil, err
	}

	pools, err := parsePgBouncer(string(out))
	if err != nil {
		return nil, err
	}

	return &PgBouncerPools{Sidecar: sc.Name, App: inst.Name, Service: pb.Service, PoolMode: pb.PoolMode, PoolSize: pb.PoolSize, Port: pb.Port, Pools: pools}, nil
}

// parsePgBouncer parses pgbouncerScript's output by column name, so columns
// added by later PgBouncer versions do not matter. PgBouncer's own admin
// database is left out: it is the console this explorer used.
func parsePgBouncer(out string) ([]PgBouncerPool, error) {
	sections := splitSections(out)

	pools, err := tsvRows(sections["pools"], "database", "user")
	if err != nil {
		return nil, fmt.Errorf("SHOW POOLS: %w", err)
	}

	stats, err := tsvRows(sections["stats"], "database")
	if err != nil {
		return nil, fmt.Errorf("SHOW STATS: %w", err)
	}

	byDB := map[string]map[string]string{}
	for _, s := range stats {
		byDB[s["database"]] = s
	}

	num := func(row map[string]string, col string) int64 {
		n, _ := strconv.ParseInt(row[col], 10, 64)

		return n
	}

	var res []PgBouncerPool

	for _, p := range pools {
		if p["database"] == "pgbouncer" {
			continue
		}

		s := byDB[p["database"]]
		res = append(res, PgBouncerPool{
			Database:       p["database"],
			User:           p["user"],
			PoolMode:       p["pool_mode"],
			ClientsActive:  num(p, "cl_active"),
			ClientsWaiting: num(p, "cl_waiting"),
			ServersActive:  num(p, "sv_active"),
			ServersIdle:    num(p, "sv_idle"),
			ServersUsed:    num(p, "sv_used"),
			ServersLogin:   num(p, "sv_login"),
			MaxWaitMicros:  num(p, "maxwait")*1_000_000 + num(p, "maxwait_us"),
			Transactions:   num(s, "total_xact_count"),
			Queries:        num(s, "total_query_count"),
			BytesReceived:  num(s, "total_received"),
			BytesSent:      num(s, "total_sent"),
			AvgQueryMicros: num(s, "avg_query_time"),
			AvgWaitMicros:  num(s, "avg_wait_time"),
		})
	}

	return res, nil
}

// tsvRows parses psql's unaligned, tab-separated output: a header line,
// then one line per row. Every column in need must be in the header.
func tsvRows(out string, need ...string) ([]map[string]string, error) {
	var (
		header []string
		rows   []map[string]string
	)

	for _, line := range strings.Split(out, "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" {
			continue
		}

		f := strings.Split(line, "\t")
		if header == nil {
			header = f
			for _, n := range need {
				if !slices.Contains(header, n) {
					return nil, fmt.Errorf("no %s column in %q", n, line)
				}
			}

			continue
		}

		row := map[string]string{}

		for i, h := range header {
			if i < len(f) {
				row[h] = f[i]
			}
		}

		rows = append(rows, row)
	}

	if header == nil {
		return nil, errors.New("no output")
	}

	return rows, nil
}
