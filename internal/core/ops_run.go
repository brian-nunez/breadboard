// Container states and health values reported in ServiceStatus.
const (
	StateNotCreated = "not created"
	HealthHealthy   = "healthy"
	HealthUnhealthy = "unhealthy"
	HealthStarting  = "starting"
)

// UpRequest starts the experiment.
type UpRequest struct {
	Dir    string
	Events EventSink
	// Timeout overrides how long to wait for health.
	Timeout time.Duration
}

// UpResult is the experiment's state once every service is healthy.
type UpResult struct {
	Experiment string
	Services   []ServiceStatus
	Warnings   []string
	// HostURLs reach the lab's host targets from the host, in route order
	// (each target, then its instances); HostPort is the 127.0.0.1 port
	// they share. Empty and zero without a host target.
	HostURLs []HostURL
	HostPort int
}

// Up reconciles state, materializes the compose project into .bb/runtime/,
// starts it, and waits until every service is healthy.
func (e *Engine) Up(ctx context.Context, req UpRequest) (*UpResult, error) {
	ev := req.Events

	if err := e.rt.Available(ctx); err != nil {
		return nil, err
	}

	p, unlock, err := e.openLocked(req.Dir, "up")
	if err != nil {
		return nil, err
	}
	defer unlock()

	if err := p.checkApps(); err != nil {
		return nil, err
	}

	if _, err := p.Ensure(e.version); err != nil {
		return nil, err
	}

	if err := e.checkOwnership(ctx, p); err != nil {
		return nil, err
	}
	// Subnets are chosen from the networks that exist now, and created by
	// compose up later; another process can create a network on the same
	// subnet in between. Docker then refuses ours, and choosing again sees
	// the newcomer and avoids it (D-181). The subnets a failed attempt chose
	// are avoided too, in case the newcomer is not listed yet (D-202).
	var (
		pr    *prepared
		avoid []netip.Prefix
	)
	for attempt := 1; ; attempt++ {
		pr, err = e.start(ctx, p, ev, avoid)
		if !errors.Is(err, runtime.ErrSubnetTaken) || attempt == subnetAttempts {
			break
		}

		if pr != nil {
			avoid = slices.AppendSeq(avoid, maps.Values(pr.subnets))
		}

		ev.emit(Event{Kind: EventInfo, Message: "Another network took a chosen subnet; choosing again"})
	}

	if err != nil {
		return nil, err
	}

	ev.step("Waiting for health checks")

	timeout := req.Timeout
	if timeout == 0 {
		timeout = e.healthTimeout
	}

	if err := e.waitHealthy(ctx, pr.model, timeout, ev); err != nil {
		return nil, err
	}

	statuses, warnings, err := e.status(ctx, pr.model, pr.hostPort)
	if err != nil {
		return nil, err
	}

	urls := hostURLs(pr.model, pr.hostPort)
	for _, u := range urls {
		to := u.Target
		if u.Instance != "" {
			to = u.Instance
		}

		ev.emit(Event{Kind: EventInfo, Service: spec.HostRouterName, Message: fmt.Sprintf("Host access: %s -> %s", u.URL, to)})
	}

	return &UpResult{Experiment: p.spec.Name, Services: statuses, Warnings: warnings, HostURLs: urls, HostPort: pr.hostPort}, nil
}

// subnetAttempts bounds how often Up chooses subnets again after Docker
// reports one taken.
const subnetAttempts = 5

// start reconciles state, writes the runtime bundle and runs compose up.
// The caller holds the project lock. When compose up fails, it returns
// the prepared project with the error, so Up can avoid its subnets.
func (e *Engine) start(ctx context.Context, p *project, ev EventSink, avoid []netip.Prefix) (*prepared, error) {
	pr, err := e.prepare(ctx, p, ev, true, avoid)
	if err != nil {
		return nil, err
	}

	ev.step("Writing the compose project")

	header := "Generated by bb from experiment.yaml. Do not edit: bb up regenerates this file."

	b, err := e.render(p, pr, p.RuntimeDir(), secrets.Inline, header)
	if err != nil {
		return nil, err
	}
	// Before anything changes: no transparent app may start as a user the
	// capture rules exempt. The check builds from a candidate copy of the
	// bundle, so a refusal leaves the active runtime files, and every
	// container mounting them, exactly as they were.
	if err := e.checkCaptureUsers(ctx, p, pr, header, ev); err != nil {
		return nil, err
	}

	if pr.networkChanged {
		// Docker cannot change a network's subnet while containers are
		// attached: stop them (data volumes stay) so compose can recreate it.
		running, err := e.rt.Containers(ctx, p.spec.Name)
		if err != nil {
			return nil, err
		}

		if len(running) > 0 {
			ev.step("Recreating the experiment's networks (their addressing changed)")
			// The project as last written: its files name the old networks.
			if err := e.rt.Down(ctx, runtimeProject(p.Project, p.spec.Name), false); err != nil {
				return nil, err
			}
		}
		// Networks the new bundle no longer declares (a retired private
		// segment) survive compose down and could hold the new subnet.
		if err := e.rt.RemoveOwned(ctx, pr.state.ExperimentID, false); err != nil {
			return nil, err
		}
	}

	if err := writeBundle(p.RuntimeDir(), b); err != nil {
		return nil, err
	}

	rp := runtimeProject(p.Project, p.spec.Name)

	ev.step("Starting containers (app images build on first run)")

	if err := e.rt.Up(ctx, rp); err != nil {
		return pr, err
	}

	return pr, nil
}

// checkCaptureUsers builds every transparent app's image and refuses one
// whose process starts as a reserved user: the capture rules exempt the
// sidecars' users (Envoy's, a registration agent's), so an app running as
// one would bypass Envoy entirely. A user name the image cannot resolve is
// refused too, since its uid cannot be checked.
func (e *Engine) checkCaptureUsers(ctx context.Context, p *project, pr *prepared, header string, ev EventSink) error {
	m := pr.model

	var apps []*model.Service

	for _, svc := range m.Services {
		if svc.Kind == model.App && svc.Transparent {
			apps = append(apps, svc)
		}
	}

	if len(apps) == 0 {
		return nil
	}

	names := make([]string, len(apps))
	for i, a := range apps {
		names[i] = a.Name
	}
	// A candidate bundle beside the active one: same project name, so the
	// images it builds are the ones up uses next.
	dir, err := os.MkdirTemp(p.StateDir(), "candidate-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(dir) }()

	b, err := e.render(p, pr, dir, secrets.Inline, header)
	if err != nil {
		return err
	}

	if err := writeBundle(dir, b); err != nil {
		return err
	}

	rp := runtime.Project{Name: "bb-" + p.spec.Name, Dir: dir, Files: []string{filepath.Join(dir, compose.ComposeFile)}}

	ev.step("Building transparent apps to check the user they run as")

	if err := e.rt.Build(ctx, rp, names); err != nil {
		return err
	}

	reserved := map[int]string{sidecar.TransparentEnvoyUID: "Envoy", sidecar.TransparentAgentUID: "the registration agent"}

	for _, a := range apps {
		u, err := e.rt.ImageUser(ctx, rp, a.Name)
		if errors.Is(err, runtime.ErrUserUnresolved) {
			return fmt.Errorf("%w: app %s runs in transparent mode, and its image starts as user %q, which cannot be resolved to a uid inside the image: set a numeric USER in %s/Dockerfile (any uid but %d and %d)",
				errs.ErrValidation, a.Group(), u.User, a.App.Path, sidecar.TransparentEnvoyUID, sidecar.TransparentAgentUID)
		}

		if err != nil {
			return err
		}

		if who, ok := reserved[u.UID]; ok {
			return fmt.Errorf("%w: app %s runs in transparent mode, and its image starts as uid %d (USER %q), which is reserved for %s: its traffic would bypass the sidecar; change USER in %s/Dockerfile to any uid but %d and %d",
				errs.ErrValidation, a.Group(), u.UID, u.User, who, a.App.Path, sidecar.TransparentEnvoyUID, sidecar.TransparentAgentUID)
		}
	}

	return nil
}

// waitHealthy polls containers until every service is running and healthy.
// It fails fast when a container exits, keeps restarting, or reports unhealthy.
func (e *Engine) waitHealthy(ctx context.Context, m *model.Model, timeout time.Duration, ev EventSink) error {
	// Wall-clock time: the injectable clock is for certificate validity.
	deadline := time.Now().Add(timeout)
	last := map[string]string{}
	// Restart counts when Up first saw each container. Any increase means the
	// program crashed during startup, even if a later poll shows it healthy.
	// Docker then reports the new run's exit code, so the error cannot say
	// how the crashed run ended; its logs can.
	baseline := map[string]int{}
	// When every service first reported healthy, and each one's start time
	// then. Success needs them to stay that way for the settle window.
	var settling time.Time

	started := map[string]time.Time{}

	for {
		list, err := e.rt.Containers(ctx, m.Name)
		if err != nil {
			return err
		}

		byService := map[string]runtime.Container{}
		for _, c := range list {
			byService[c.Service] = c
		}

		pending := []string{}

		for _, svc := range m.Services {
			c, ok := podState(svc, byService)

			h := health(c, ok)
			if h != last[svc.Name] {
				last[svc.Name] = h
				ev.emit(Event{Kind: EventHealth, Service: svc.Name, Health: h, Message: fmt.Sprintf("%s: %s", svc.Name, h)})
			}

			for _, name := range containerNames(svc) {
				rc, ok := byService[name]
				if !ok {
					continue
				}

				what := svc.Name
				if name != svc.Name {
					what = fmt.Sprintf("%s's network holder %s", svc.Name, name)
				}

				if n, seen := baseline[name]; !seen {
					baseline[name] = rc.RestartCount
				} else if rc.RestartCount > n {
					return fmt.Errorf("%s restarted during startup%s; see bb logs %s for why: %w", what, oom(rc), svc.Name, ErrUnhealthy)
				}

				if t, seen := started[name]; seen && !rc.StartedAt.Equal(t) {
					return fmt.Errorf("%s restarted during startup%s; see bb logs %s for why: %w", what, oom(rc), svc.Name, ErrUnhealthy)
				}
			}

			switch {
			case h == HealthHealthy:
			case h == HealthUnhealthy:
				return fmt.Errorf("%s failed its health check; see bb logs %s: %w", svc.Name, svc.Name, ErrUnhealthy)
			case ok && (c.State == "exited" || c.State == "dead"):
				return fmt.Errorf("%s exited with code %d%s; see bb logs %s: %w", svc.Name, c.ExitCode, oom(c), svc.Name, ErrUnhealthy)
			case ok && c.State == "restarting":
				return fmt.Errorf("%s is restarting (exit code %d%s); see bb logs %s: %w", svc.Name, c.ExitCode, oom(c), svc.Name, ErrUnhealthy)
			default:
				pending = append(pending, svc.Name)
			}
		}

		switch {
		case len(pending) > 0:
			// Not all healthy (yet, or any more): the settle window restarts.
			settling = time.Time{}

			clear(started)
		case settling.IsZero():
			settling = time.Now()

			for _, svc := range m.Services {
				for _, name := range containerNames(svc) {
					started[name] = byService[name].StartedAt
				}
			}

			if e.startupSettle < 0 {
				return nil
			}
		case time.Since(settling) >= e.startupSettle:
			return nil
		}

		if time.Now().After(deadline) {
			waiting := strings.Join(pending, ", ")
			if waiting == "" {
				waiting = "services to stay healthy"
			}

			return fmt.Errorf("timed out after %s waiting for %s: %w", timeout, waiting, ErrUnhealthy)
		}

		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(e.pollInterval):
		}
	}
}

// containerNames lists the containers whose state a service's state
// includes: its own, and for an app in a pod, the pod's namespace holder.
func containerNames(svc *model.Service) []string {
	if svc.Pod != "" {
		return []string{svc.Name, svc.Pod}
	}

	return []string{svc.Name}
}

// podState is the container that decides a service's state. For an app in
// a pod, the namespace holder decides while it is missing, not running, or
// not healthy, since the app has no network without it; the holder is
// never reported as a service of its own.
func podState(svc *model.Service, byService map[string]runtime.Container) (runtime.Container, bool) {
	c, ok := byService[svc.Name]
	if svc.Pod == "" {
		return c, ok
	}

	if hc, hok := byService[svc.Pod]; health(hc, hok) != HealthHealthy {
		return hc, hok
	}

	return c, ok
}

func oom(c runtime.Container) string {
	if c.OOMKilled {
		return ", killed for exceeding its memory limit"
	}

	return ""
}

// health summarises a container as one word.
func health(c runtime.Container, exists bool) string {
	switch {
	case !exists:
		return StateNotCreated
	case c.State != "running":
		return c.State
	case c.Health == "":
		return HealthHealthy // no health check: running is the best signal
	}

	return c.Health
}

// DownRequest stops the experiment.
type DownRequest struct {
	Dir     string
	Volumes bool // also delete data volumes
	Events  EventSink
}

// DownResult reports what was stopped.
type DownResult struct {
	Experiment     string
	VolumesRemoved bool
}

// Down stops and removes the experiment's containers and networks, and with
// Volumes its data.
func (e *Engine) Down(ctx context.Context, req DownRequest) (*DownResult, error) {
	if err := e.rt.Available(ctx); err != nil {
		return nil, err
	}

	p, unlock, err := e.openLocked(req.Dir, "down")
	if err != nil {
		return nil, err
	}
	defer unlock()

	if _, err := p.Ensure(e.version); err != nil {
		return nil, err
	}

	if err := e.checkOwnership(ctx, p); err != nil {
		return nil, err
	}

	ps, err := p.LoadState()
	if err != nil {
		return nil, err
	}

	req.Events.step("Stopping containers")

	if err := e.rt.Down(ctx, runtimeProject(p.Project, p.spec.Name), req.Volumes); err != nil {
		return nil, err
	}
	// Networks and volumes of services removed since an earlier up are no
	// longer in the compose files, so compose leaves them behind.
	if err := e.rt.RemoveOwned(ctx, ps.ExperimentID, req.Volumes); err != nil {
		return nil, err
	}

	return &DownResult{Experiment: p.spec.Name, VolumesRemoved: req.Volumes}, nil
}

// ServiceStatus is one service's live state.
type ServiceStatus struct {
	Name        string
	Kind        string // infra, app, or sidecar
	Type        string // catalog type for infra; empty for apps
	Image       string
	Address     string
	State       string // running, exited, ..., or "not created"
	Health      string // healthy, starting, unhealthy, or the state when not running
	CPUPercent  float64
	CPULimit    string
	MemoryBytes uint64
	MemoryLimit string // the configured limit, e.g. 512m
	OOMKilled   bool
	StartedAt   time.Time
	Uses        []Edge
	// Apps only: the source directory and command from experiment.yaml.
	Path    string
	Command []string
	// App instances only: the app in experiment.yaml, the instance number
	// (0 when the app runs one replica), how many replicas the app runs,
	// and the instance's sidecars by service name. Each instance's row is
	// followed by its sidecars' rows; the pod's namespace holder is never a
	// row, but its state counts toward the instance's State and Health.
	App      string
	Instance int
	Replicas int
	Sidecars []string
	// Sidecars only: the app instance whose pod they share, the registry an
	// agent joins, and what the sidecar is (ports, env, mode).
	Parent   string
	Registry string
	Sidecar  *SidecarInfo
	// HostURLs reach the service from the host (ADR-0017): an app
	// instance's app URL, then its own URL when the app has replicas; an
	// infra target's URL. Empty without host access or before the first
	// bb up records the port.
	HostURLs []string
	// HostRouter marks the lab's host router (bb-host).
	HostRouter bool
}

// Edge is a connection from an app to a service, through an Envoy
// sidecar's outbound listener to another app or a service, or from a proxy
// to one of its upstreams.
type Edge struct {
	To     string
	Port   int
	TLS    bool
	Reason string
	// Via is the Envoy sidecar (its name within the app) that carries the
	// edge; empty for an edge from uses.
	Via string
	// ToApp marks an edge to an app; To is then the target app's name.
	ToApp bool
	// Mode is set on a proxy's upstream edges (Phase 5): on (re-encrypt,
	// TLS), off (terminate; plaintext on a private segment) or passthrough.
	Mode string
	// Discovery is set on the edges of a proxy that discovers routes in a
	// service registry: registry (to the registry) or route (to an app
	// registered there for the proxy).
	Discovery string
}

// StatusRequest asks for the experiment's state.
type StatusRequest struct {
	Dir string
}

// StatusResult is the experiment's state.
type StatusResult struct {
	Experiment string
	Domain     string
	Services   []ServiceStatus
	Warnings   []string
	// HostURLs and HostPort as in UpResult.
	HostURLs []HostURL
	HostPort int
}

// Status reports every service's state, health, and resource use, plus
// warnings such as plaintext edges.
func (e *Engine) Status(ctx context.Context, req StatusRequest) (*StatusResult, error) {
	if err := e.rt.Available(ctx); err != nil {
		return nil, err
	}

	p, err := e.open(req.Dir)
	if err != nil {
		return nil, err
	}

	st, err := e.settings(ctx)
	if err != nil {
		return nil, err
	}

	m, err := model.Resolve(p.spec, st.Domain)
	if err != nil {
		return nil, err
	}

	port := 0
	if _, ok := m.HostRouter(); ok {
		port = recordedHostPort(p)
	}

	statuses, warnings, err := e.status(ctx, m, port)
	if err != nil {
		return nil, err
	}

	res := &StatusResult{Experiment: m.Name, Domain: m.Domain, Services: statuses, Warnings: warnings, HostURLs: hostURLs(m, port)}
	if len(res.HostURLs) > 0 {
		res.HostPort = port
	}

	return res, nil
}

// status describes every service; hostPort is the host router's port, or
// zero when unknown.
func (e *Engine) status(ctx context.Context, m *model.Model, hostPort int) ([]ServiceStatus, []string, error) {
	list, err := e.rt.Containers(ctx, m.Name)
	if err != nil {
		return nil, nil, err
	}

	byService := map[string]runtime.Container{}

	var running []string

	for _, c := range list {
		byService[c.Service] = c
		if c.State == "running" {
			running = append(running, c.ID)
		}
	}

	usage, err := e.usage(ctx, running)
	if err != nil {
		return nil, nil, err
	}

	infos := map[string]*SidecarInfo{}

	for _, svc := range m.Services {
		list, err := sidecarInfos(m, svc)
		if err != nil {
			return nil, nil, err
		}

		for i := range list {
			infos[list[i].Service] = &list[i]
		}
	}

	var (
		out      []ServiceStatus
		warnings []string
	)

	for _, svc := range m.Services {
		c, ok := byService[svc.Name]
		pc, pok := podState(svc, byService)

		s := ServiceStatus{
			Name:        svc.Name,
			Kind:        string(svc.Kind),
			Address:     listenerAddress(svc),
			State:       StateNotCreated,
			Health:      health(pc, pok),
			CPULimit:    svc.Resources.CPUs,
			MemoryLimit: svc.Resources.Memory,
			HostURLs:    serviceHostURLs(m, svc, hostPort),
			HostRouter:  svc.HostRouter,
		}
		switch svc.Kind {
		case model.Infra:
			s.Type, s.Image = svc.Entry.ID, svc.Entry.Image
		case model.App:
			s.Path, s.Command = svc.App.Path, svc.App.Command
			s.App, s.Instance, s.Replicas, s.Sidecars = svc.Group(), svc.Instance, svc.App.ReplicaCount(), svc.Sidecars
		case model.Sidecar:
			s.Image, s.Parent, s.Registry, s.Sidecar = svc.Image, svc.Parent, svc.Registry, infos[svc.Name]
			if svc.SidecarType != nil {
				s.Type = svc.SidecarType.ID
			}
		}
		// State and Health come from the same container: the app's, or its
		// pod holder's while the holder is missing or unhealthy (then the
		// app has no network either). Resource figures stay the app's own.
		if pok {
			s.State = pc.State
		}

		if ok {
			s.OOMKilled, s.StartedAt = c.OOMKilled, c.StartedAt
			if c.Image != "" {
				s.Image = c.Image
			}

			if u, ok := usage[c.ID]; ok {
				s.CPUPercent, s.MemoryBytes = u.CPUPercent, u.MemoryBytes
			}

			if c.OOMKilled {
				warnings = append(warnings, fmt.Sprintf("%s was killed for exceeding its %s memory limit", svc.Name, svc.Resources.Memory))
			}
		}

		if svc.Kind != model.Sidecar {
			// An app's edges, or a proxy's upstream and discovery edges.
			for _, edge := range m.EdgesFrom(svc.Group()) {
				s.Uses = append(s.Uses, Edge{To: edge.To, Port: edge.Port, TLS: edge.TLS, Reason: edge.Reason, Via: edge.Via, ToApp: edge.ToApp, Mode: edge.Mode, Discovery: edge.Discovery})
			}
		}

		out = append(out, s)
	}

	for _, edge := range m.PlaintextEdges() {
		warnings = append(warnings, fmt.Sprintf("plaintext edge %s -> %s:%d (tls.mode: off): %s", edge.From, edge.To, edge.Port, edge.Reason))
	}

	return out, warnings, nil
}

// LogsRequest asks for service output.
type LogsRequest struct {
	Dir     string
	Service string // empty means every service
	Follow  bool
	Tail    int // lines per service; zero means all
}

// LogLine is one line of output.
type LogLine struct {
	Service string
	Text    string
}

// Logs streams service output. The stream ends when the logs end or, with
// Follow, when ctx is cancelled.
func (e *Engine) Logs(ctx context.Context, req LogsRequest) (iter.Seq2[LogLine, error], error) {
	if err := e.rt.Available(ctx); err != nil {
		return nil, err
	}

	p, err := e.open(req.Dir)
	if err != nil {
		return nil, err
	}

	var services []string

	if req.Service != "" {
		names := make([]string, 0, len(p.spec.Services)+len(p.spec.Apps))
		for _, s := range p.spec.Services {
			names = append(names, s.Name)
		}

		for _, a := range p.spec.Apps {
			names = append(names, a.Name)
		}
		// An app's instances and sidecars are containers of their own; an app
		// with replicas means all of its instances.
		containers := map[string][]string{}

		for _, a := range p.spec.Apps {
			insts := a.Instances()
			if len(insts) > 1 {
				containers[a.Name] = insts
			}

			for _, inst := range insts {
				containers[inst] = []string{inst}
				for _, sc := range a.Sidecars {
					n := spec.SidecarServiceName(inst, sc.ID())
					containers[n] = []string{n}
				}

				if a.Register != nil {
					containers[spec.SidecarName(inst)] = []string{spec.SidecarName(inst)}
				}
			}
		}

		switch {
		case containers[req.Service] != nil:
			services = containers[req.Service]
		case slices.Contains(names, req.Service):
			services = []string{req.Service}
		default:
			return nil, fmt.Errorf("%q is not a service or app (have: %s): %w", req.Service, strings.Join(names, ", "), ErrNotFound)
		}
	}

	src := e.rt.Logs(ctx, runtimeProject(p.Project, p.spec.Name), services, req.Follow, req.Tail)

	return func(yield func(LogLine, error) bool) {
		for l, err := range src {
			if !yield(LogLine{Service: l.Service, Text: l.Text}, err) {
				return
			}
		}
	}, nil
}
