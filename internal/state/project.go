package state

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"time"
)

// Format versions of the project state files.
const (
	StateFormat   = 1
	SecretsFormat = 1
)

// Directory and file names inside a project.
const (
	DirName     = ".bb"
	stateFile   = "state.json"
	secretsFile = "secrets.json"
	lockFile    = "lock"
	certsDir    = "certs"
	runtimeDir  = "runtime"
)

// Upgrade steps, keyed by the version they upgrade from. Format 1 is the
// first, so there are none yet.
var (
	stateUpgrades   = map[int]upgradeStep{}
	secretsUpgrades = map[int]upgradeStep{}
)

// Project is one experiment's directory and its .bb/ state.
type Project struct {
	Dir string // the directory holding experiment.yaml
}

// StateDir is the project's .bb directory.
func (p Project) StateDir() string { return filepath.Join(p.Dir, DirName) }

// RuntimeDir holds the generated compose project.
func (p Project) RuntimeDir() string { return filepath.Join(p.StateDir(), runtimeDir) }

func (p Project) path(name ...string) string {
	return filepath.Join(append([]string{p.StateDir()}, name...)...)
}

// ProjectState is .bb/state.json.
type ProjectState struct {
	FormatVersion int    `json:"formatVersion"`
	BBVersion     string `json:"bbVersion"`
	ExperimentID  string `json:"experimentId"`
	// Certificates records which CA issued each service's leaf.
	Certificates map[string]CertRecord `json:"certificates"`
	// Segments maps each private network segment to its allocated subnet.
	Segments map[string]string `json:"segments"`
}

// CertRecord describes an issued leaf certificate.
type CertRecord struct {
	Issuer   string    `json:"issuer"`
	Serial   string    `json:"serial"`
	NotAfter time.Time `json:"notAfter"`
}

// Secrets is .bb/secrets.json: generated values per service.
type Secrets struct {
	FormatVersion int                          `json:"formatVersion"`
	Services      map[string]map[string]string `json:"services"`
}

// Get returns a service's secret.
func (s *Secrets) Get(service, key string) (string, bool) {
	v, ok := s.Services[service][key]
	return v, ok
}

// Set stores a service's secret.
func (s *Secrets) Set(service, key, value string) {
	if s.Services == nil {
		s.Services = map[string]map[string]string{}
	}
	if s.Services[service] == nil {
		s.Services[service] = map[string]string{}
	}
	s.Services[service][key] = value
}

// Ensure creates any missing part of .bb/: the directory (0700) with its
// self-ignoring .gitignore, the certs and runtime directories, state.json,
// and secrets.json (0600). Existing files are left alone. It reports whether
// the .bb directory itself was created.
func (p Project) Ensure(bbVersion string) (created bool, err error) {
	if _, err := os.Stat(p.StateDir()); errors.Is(err, os.ErrNotExist) {
		created = true
	}
	for _, dir := range []string{p.StateDir(), p.path(certsDir), p.RuntimeDir()} {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return false, fmt.Errorf("create %s: %w", dir, err)
		}
		if err := os.Chmod(dir, 0o700); err != nil {
			return false, fmt.Errorf("chmod %s: %w", dir, err)
		}
	}
	ignore := p.path(".gitignore")
	if _, err := os.Stat(ignore); errors.Is(err, os.ErrNotExist) {
		if err := WriteFile(ignore, []byte("# Generated by bb: secrets and certificates never leave this machine.\n*\n"), 0o644); err != nil {
			return false, err
		}
	}
	if _, err := os.Stat(p.path(stateFile)); errors.Is(err, os.ErrNotExist) {
		id := make([]byte, 8)
		if _, err := rand.Read(id); err != nil {
			return false, err
		}
		st := &ProjectState{ExperimentID: hex.EncodeToString(id)}
		if err := p.SaveState(st, bbVersion); err != nil {
			return false, err
		}
	}
	if _, err := os.Stat(p.path(secretsFile)); errors.Is(err, os.ErrNotExist) {
		if err := p.SaveSecrets(&Secrets{}); err != nil {
			return false, err
		}
	}
	return created, nil
}

// Lock takes the project's exclusive operation lock, or returns a *BusyError.
func (p Project) Lock(operation string) (*Lock, error) {
	if err := os.MkdirAll(p.StateDir(), 0o700); err != nil {
		return nil, err
	}
	return acquire(p.path(lockFile), operation)
}

// LoadState reads state.json, upgrading older formats in memory.
func (p Project) LoadState() (*ProjectState, error) {
	st := &ProjectState{}
	if _, err := loadJSON(p.path(stateFile), StateFormat, stateUpgrades, st); err != nil {
		return nil, err
	}
	if st.Certificates == nil {
		st.Certificates = map[string]CertRecord{}
	}
	if st.Segments == nil {
		st.Segments = map[string]string{}
	}
	return st, nil
}

// SaveState writes state.json, stamping the format and the bb version.
func (p Project) SaveState(st *ProjectState, bbVersion string) error {
	st.FormatVersion = StateFormat
	st.BBVersion = bbVersion
	return saveJSON(p.path(stateFile), StateFormat, st, 0o600)
}

// LoadSecrets reads secrets.json.
func (p Project) LoadSecrets() (*Secrets, error) {
	s := &Secrets{}
	if _, err := loadJSON(p.path(secretsFile), SecretsFormat, secretsUpgrades, s); err != nil {
		return nil, err
	}
	if s.Services == nil {
		s.Services = map[string]map[string]string{}
	}
	return s, nil
}

// SaveSecrets writes secrets.json with mode 0600.
func (p Project) SaveSecrets(s *Secrets) error {
	s.FormatVersion = SecretsFormat
	if s.Services == nil {
		s.Services = map[string]map[string]string{}
	}
	return saveJSON(p.path(secretsFile), SecretsFormat, s, 0o600)
}

// ReadCert returns a service's stored certificate and key, or ok=false.
func (p Project) ReadCert(service string) (certPEM, keyPEM []byte, ok bool, err error) {
	certPEM, err = os.ReadFile(p.path(certsDir, service, "tls.crt"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil, false, nil
	}
	if err != nil {
		return nil, nil, false, err
	}
	keyPEM, err = os.ReadFile(p.path(certsDir, service, "tls.key"))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil, false, nil
	}
	if err != nil {
		return nil, nil, false, err
	}
	return certPEM, keyPEM, true, nil
}

// WriteCert stores a service's certificate (0644) and key (0600).
func (p Project) WriteCert(service string, certPEM, keyPEM []byte) error {
	dir := p.path(certsDir, service)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	if err := WriteFile(filepath.Join(dir, "tls.key"), keyPEM, 0o600); err != nil {
		return err
	}
	return WriteFile(filepath.Join(dir, "tls.crt"), certPEM, 0o644)
}

// RemoveCert deletes a service's stored certificate, if any.
func (p Project) RemoveCert(service string) error {
	return os.RemoveAll(p.path(certsDir, service))
}

// CertServices lists services with a stored certificate.
func (p Project) CertServices() ([]string, error) {
	entries, err := os.ReadDir(p.path(certsDir))
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() {
			out = append(out, e.Name())
		}
	}
	return out, nil
}
